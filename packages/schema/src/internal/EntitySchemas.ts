/** A plain record — what unmarshalling produces, as opposed to a class instance. */
const isPlainObject = (value: unknown): value is globalThis.Record<string, unknown> => {
  if (value === null || typeof value !== "object") return false
  const proto = Object.getPrototypeOf(value)
  return proto === Object.prototype || proto === null
}

/**
 * A real `DateTime` instance. `DateTime.isDateTime` checks for the type-id
 * property only, so a plain object read back from a marshalled instance passes
 * it too (#133) — and is then neither `Equal` to the instant nor usable with the
 * `DateTime` API that relies on the prototype.
 */
const isGenuineDateTime = (value: unknown): value is DateTime.DateTime =>
  DateTime.isDateTime(value) && !isPlainObject(value)

/**
 * Convert any input value (string / number / DateTime / Date) to the wire
 * primitive for a given encoding. Used by date substitutes' `encode` path.
 *
 * Wire format precisely matches the legacy `serializeDateForDynamo` output:
 * - `string` storage → ISO 8601 string (UTC for DateTime.Utc / Date; extended
 *   format for DateTime.Zoned)
 * - `epochMs` storage → integer milliseconds since the Unix epoch
 * - `epochSeconds` storage → integer seconds since the Unix epoch (TTL format)
 */
const toWirePrimitive = (input: unknown, encoding: DynamoEncoding): string | number => {
  const value = reviveMarshalledDateTime(input) ?? input
  let epochMs: number
  let zoned: DateTime.Zoned | undefined
  if (DateTime.isDateTime(value)) {
    if (DateTime.isZoned(value)) zoned = value
    epochMs = DateTime.toEpochMillis(value)
  } else if (value instanceof Date) {
    epochMs = value.getTime()
  } else if (typeof value === "string") {
    epochMs = new Date(value).getTime()
  } else if (typeof value === "number") {
    // Numeric inputs are interpreted in the encoding's storage scale already.
    if (encoding.storage === "epochSeconds") epochMs = value * 1000
    else epochMs = value
  } else {
    throw new Error(
      `[effect-dynamodb] toWirePrimitive: unsupported input ${typeof value} for ${encoding.domain}/${encoding.storage}`,
    )
  }
  switch (encoding.storage) {
    case "string":
      if (encoding.domain === "DateTime.Zoned" && zoned) return zonedIsoText(zoned)
      return new Date(epochMs).toISOString()
    case "epochMs":
      return epochMs
    case "epochSeconds":
      return Math.floor(epochMs / 1000)
  }
}

/**
 * Build a bidirectional Schema for a given DynamoEncoding.
 *
 * The encoded side is `Schema.Any` so `decode` tolerates either:
 * - the wire primitive (string / number) — the storage-shape input, OR
 * - a domain value (`DateTime.Utc`, `Date`, etc.) — what users typically pass
 *   into `entity.put({...})` and `.set({...})`.
 *
 * The `decode` direction always lifts to the domain type (DateTime.Utc /
 * DateTime.Zoned / Date). The `encode` direction always produces the wire
 * primitive. This makes both `Schema.encode(substituted)` and
 * `Schema.decode(substituted)` work end-to-end regardless of whether the
 * caller passed wire-form or domain-form.
 *
 * @internal
 */
export const buildDateTransform = (
  encoding: DynamoEncoding,
  options?: {
    /**
     * Accept only this encoding's OWN wire kind (a string for `string` storage, a
     * number for epoch storage), a domain value of this encoding's domain, or a
     * legacy marshalled map of it — never a cross-kind input. Used for date leaves
     * reached through a `Union`: there the tolerant decode is tried member by
     * member, and accepting any date-ish input would let a date member claim a
     * value that belongs to a later member (a stored `5` in
     * `Union([DateTimeUtcFromString, Number])` would read back as a `DateTime`).
     */
    readonly strictWireKind?: boolean | undefined
    /**
     * With `strictWireKind`: accept a wire primitive only in the exact
     * canonical form `toWirePrimitive` writes. Set when another member of the
     * same union encodes to the same primitive kind (a `String` member next to
     * ISO storage): any string that is not this date's own canonical
     * spelling — `"2020"`, `"5"` — is left for that member, as it was before
     * dates were written in wire form (#133).
     */
    readonly canonicalOnly?: boolean | undefined
  },
): Schema.Top => {
  const strict = options?.strictWireKind === true
  const canonicalOnly = options?.canonicalOnly === true
  const targetSchema = (() => {
    switch (encoding.domain) {
      case "DateTime.Utc":
        return Schema.DateTimeUtc as unknown as Schema.Top
      case "DateTime.Zoned":
        return Schema.DateTimeZoned as unknown as Schema.Top
      case "Date":
        return Schema.Date as unknown as Schema.Top
    }
  })()
  const fromDateTime = (value: DateTime.DateTime): unknown => {
    switch (encoding.domain) {
      case "DateTime.Utc":
        return DateTime.toUtc(value)
      case "DateTime.Zoned":
        return DateTime.isZoned(value)
          ? value
          : DateTime.makeZonedUnsafe(DateTime.toEpochMillis(value), { timeZone: "UTC" })
      case "Date":
        return DateTime.toDateUtc(value)
    }
  }
  /** Under `strictWireKind`: whether a DateTime is of this encoding's own domain. */
  const ownDomain = (value: DateTime.DateTime): boolean =>
    encoding.domain === "DateTime.Utc"
      ? DateTime.isUtc(value)
      : encoding.domain === "DateTime.Zoned" && DateTime.isZoned(value)
  const liftStrict = (value: unknown): unknown => {
    const revived = reviveMarshalledDateTime(value)
    if (revived !== undefined) {
      if (ownDomain(revived)) return revived
      throw new Error("[effect-dynamodb] marshalled DateTime of another domain")
    }
    if (isGenuineDateTime(value) && ownDomain(value)) return value
    if (value instanceof Date && encoding.domain === "Date" && !Number.isNaN(value.getTime())) {
      return value
    }
    if (typeof value === (encoding.storage === "string" ? "string" : "number")) {
      const lifted = liftToDomain(value)
      if (lifted instanceof Date && Number.isNaN(lifted.getTime())) {
        throw new Error("[effect-dynamodb] invalid date")
      }
      if (canonicalOnly && toWirePrimitive(lifted, encoding) !== value) {
        throw new Error("[effect-dynamodb] not this date member's canonical wire form")
      }
      return lifted
    }
    throw new Error("[effect-dynamodb] not this date member's wire or domain form")
  }
  const liftToDomain = (value: unknown): unknown => {
    // A marshalled `DateTime` instance (#133) — rebuilt, whatever type-id key
    // the Effect version that wrote it used.
    const revived = reviveMarshalledDateTime(value)
    if (revived !== undefined) return fromDateTime(revived)
    if (DateTime.isDateTime(value)) {
      if (isGenuineDateTime(value)) return value
      // Duck-types as a DateTime but carries no recoverable instant: refuse it
      // rather than hand a plain object to the domain.
      throw new Error("[effect-dynamodb] unrecoverable marshalled DateTime")
    }
    if (value instanceof Date) {
      switch (encoding.domain) {
        case "DateTime.Utc":
          return DateTime.makeUnsafe(value)
        case "DateTime.Zoned":
          return DateTime.makeZonedUnsafe(value, { timeZone: "UTC" })
        case "Date":
          return value
      }
    }
    if (typeof value === "string") {
      switch (encoding.domain) {
        case "DateTime.Utc":
          return DateTime.makeUnsafe(value)
        case "DateTime.Zoned":
          // Named and offset zones are both rebuilt as written (#133).
          return parseZonedIso(value)
        case "Date":
          return new Date(value)
      }
    }
    if (typeof value === "number") {
      const ms = encoding.storage === "epochSeconds" ? value * 1000 : value
      switch (encoding.domain) {
        case "DateTime.Utc":
          return DateTime.makeUnsafe(ms)
        case "DateTime.Zoned":
          return DateTime.makeZonedUnsafe(new Date(ms), { timeZone: "UTC" })
        case "Date":
          return new Date(ms)
      }
    }
    return value
  }
  return Schema.Any.pipe(
    Schema.decodeTo(targetSchema, {
      decode: SchemaGetter.transformEffect((value: unknown) => {
        try {
          return Effect.succeed(strict ? liftStrict(value) : liftToDomain(value))
        } catch {
          return Effect.fail(new SchemaIssue.InvalidType(Schema.Any.ast, value))
        }
      }),
      encode: SchemaGetter.transformEffect((value: unknown) => {
        try {
          return Effect.succeed(toWirePrimitive(value, encoding))
        } catch {
          return Effect.fail(new SchemaIssue.InvalidType(Schema.Any.ast, value))
        }
      }),
    } as any),
  ) as unknown as Schema.Top
}

/**
 * Detects `Schema.RedactedFromValue(inner)` fields (and `Schema.Redacted`).
 * The encoded form of these schemas is "Forbidden" by Effect v4 design —
 * encoding bails out to prevent accidental leaks. To make the round-trip work
 * for our use case (write to DynamoDB, read back with Redacted on the domain
 * side), we substitute with a custom transform that explicitly extracts the
 * inner value via `Redacted.value` on encode and rewraps via `Redacted.make`
 * on decode.
 *
 * Returns the inner schema (the wire-format schema) when the field is a
 * Redacted-typed schema, otherwise undefined.
 */
const tryGetRedactedInner = (schema: Schema.Top): Schema.Top | undefined => {
  const resolved = SchemaAST.resolve(schema.ast) as { representation?: { id?: string } } | undefined
  if (resolved?.representation?.id !== "effect/schema/Redacted") return undefined
  // The decoded type is `Redacted<T>` where the inner schema is the first type
  // parameter. `firstTypeParameterAst` isolates that single untyped AST read
  // (no public accessor exists); we then rebuild a fully-functional Schema via
  // `Schema.make` so the result has `.pipe`.
  const innerAst = firstTypeParameterAst(schema.ast)
  if (!innerAst) return undefined
  return Schema.make<Schema.Top>(innerAst)
}

/**
 * Build a substitute Schema for a `Schema.RedactedFromValue(inner)` field.
 *
 * The substitute round-trips: produces `Redacted<T>` on the domain side and
 * the inner wire primitive on the encoded side. Both directions tolerate
 * either form on input — a user passing a plain inner value is wrapped via
 * `Redacted.make`; a user passing a `Redacted<T>` instance is unwrapped on
 * encode via `Redacted.value`. This permissive shape lets the put/update
 * paths handle the mixed wire/domain payloads users typically construct
 * (e.g. `.put({ secret: Redacted.make(...) })`).
 *
 * The encoded side is `Schema.Any` so decode tolerates either form; the
 * branch logic in `decode`/`encode` then steers the value to the right
 * representation.
 */
const buildRedactedSubstitute = (schema: Schema.Top, inner: Schema.Top): Schema.Top => {
  const resolved = SchemaAST.resolve(schema.ast) as
    | { readonly representation?: { readonly payload?: { readonly label?: unknown } | null } }
    | undefined
  const declared = resolved?.representation?.payload?.label
  const label = typeof declared === "string" ? declared : undefined
  return Schema.Any.pipe(
    Schema.decodeTo(
      Schema.Redacted(inner) as unknown as Schema.Top,
      {
        decode: SchemaGetter.transform((value: unknown) =>
          Redacted.isRedacted(value) ? value : Redacted.make(value, { label }),
        ),
        encode: SchemaGetter.transform((r: unknown) =>
          Redacted.isRedacted(r) ? Redacted.value(r as Redacted.Redacted<unknown>) : r,
        ),
      } as any,
    ),
  ) as unknown as Schema.Top
}

/** A schema that exposes declared fields (Schema.Struct or Schema.Class). */
const schemaFieldsOf = (schema: Schema.Top): SchemaFields | undefined =>
  (schema as unknown as { readonly fields?: SchemaFields }).fields

/**
 * A LEAF encoding transformation — one whose Type and Encoded forms differ and
 * which is not itself a container. Containers (Struct / Class / Array) are
 * handled by `substituteSchemaDeep`'s own recursion, and dates / Redacted have
 * their own dedicated substitutes, so those are excluded by the caller's branch
 * ordering rather than here.
 */
const isLeafEncodingTransform = (schema: Schema.Top): boolean =>
  schemaFieldsOf(schema) === undefined &&
  !isArraySchema(schema) &&
  transformWireKindImpl(schema) !== undefined

/**
 * What an aggregate takes in either form: any transformation that isn't a class or a struct, whose
 * fields are walked, whatever it's stored as, such as `Schema.Defect()`, a `Schema.toCodecJson` over
 * a map, a map decoded from a record, `Schema.OptionFromNullOr` or a list held as JSON. A step
 * encoded as optional has been unwrapped by now (`decodingDefaultField`), and it has to keep filling
 * a missing key. A list whose elements are substituted is walked from its type side, whatever it's
 * stored as, as an entity's is: what that stores decides what's in rows already written.
 */
const isTolerantLeaf = (schema: Schema.Top): boolean => {
  if (schemaFieldsOf(schema) !== undefined || schema.ast.encoding === undefined) return false
  if (!SchemaAST.isArrays(schema.ast) || schema.ast.elements.length > 0) return true
  const element = arrayElementOf(schema)
  return element === undefined || !needsDeepSubstitution(element, { tolerantTransforms: true })
}

/**
 * Build a TOLERANT substitute for an arbitrary leaf transform — the general
 * form of what `buildDateTransform` does for dates.
 *
 * Only reachable under `tolerantTransforms`, i.e. only from an aggregate's
 * schemas. An aggregate's `create` and `update` decode what a caller holds, the
 * domain value (a `bigint` for a `Schema.BigIntFromString`), where a strict
 * transform accepts only the wire value (the string), so any update on such a
 * model failed before an item was ever built — regardless of which field the
 * mutation touched.
 *
 * **Tolerant, not lax.** Decode tries the transform first (wire form), then
 * validates the value against the transform's own TYPE side (domain form). A
 * value that is neither is still rejected, exactly as before — this widens the
 * accepted input, it does not skip validation.
 *
 * `domainFirst` asks the domain side first, for a value a caller holds (see `domainValues`). What
 * both sides take is the domain value, and comes out as what reading its stored form gives, as it
 * would from an entity: a transformation lowercasing on decode gives the same text either way.
 *
 * `plainForm` also takes what a mutation's plain state holds for that domain (see `plainStateForms`),
 * asked before the stored side: a set held as a list is a domain value, even where what's stored is a list.
 *
 * `domainStored`: for a type side that takes anything (`takesAnything`), any value it takes is a
 * domain value only where the transform stores it, whether or not the transform also reads it as
 * stored. `Unknown` takes another union member's value, a `many` element its ref fetch changed, or a
 * field's stored form; 1.39.0 read those through the member's own struct or the transform, or refused
 * them, and `create` returns what it did.
 */
const buildTolerantTransform = (
  schema: Schema.Top,
  domainFirst = false,
  plainForm?: Schema.Top,
  domainStored = false,
): Schema.Top => {
  const typeSide = Schema.make<Schema.Top>(SchemaAST.toType(schema.ast))
  const codec = schema as unknown as Schema.Codec<any>
  const decodeWire = Schema.decodeUnknownOption(codec)
  const encodeDomain = Schema.encodeUnknownOption(codec)
  const validateType = Schema.decodeUnknownOption(typeSide as unknown as Schema.Codec<any>)
  // A transform's `encode` is the caller's own code, written for its domain values only.
  const stores = (value: unknown): boolean => {
    try {
      return encodeDomain(value)._tag === "Some"
    } catch {
      return false
    }
  }
  const validateDomain = (value: unknown): Option.Option<unknown> => {
    const typed = validateType(value)
    return domainStored && typed._tag === "Some" && !stores(typed.value) ? Option.none() : typed
  }
  const bigintDomain = SchemaAST.isBigInt(SchemaAST.toType(schema.ast))
  const decodePlain =
    plainForm === undefined
      ? undefined
      : Schema.decodeUnknownOption(Schema.toCodecIso(plainForm as never) as Schema.Codec<any>)

  return Schema.Any.pipe(
    Schema.decodeTo(typeSide, {
      decode: SchemaGetter.transformEffect((value: unknown) => {
        if (domainFirst) {
          const given = validateDomain(reviveMarshalledDateTime(value) ?? value)
          if (given._tag === "Some") {
            const read =
              decodeWire(value)._tag === "Some"
                ? Option.flatMap(encodeDomain(given.value), decodeWire)
                : given
            return Effect.succeed(read._tag === "Some" ? read.value : given.value)
          }
        }
        const plain = decodePlain?.(value)
        if (plain?._tag === "Some") return Effect.succeed(plain.value)
        const fromWire = decodeWire(value)
        if (fromWire._tag === "Some") return Effect.succeed(fromWire.value)
        // A marshalled `DateTime` (#133) is rebuilt before it is validated: a
        // 4.0.0-era map would otherwise pass a `DateTime` check by duck typing
        // and come back as a plain object.
        const revived = reviveMarshalledDateTime(value)
        const alreadyDomain = validateDomain(revived ?? value)
        if (alreadyDomain._tag === "Some") return Effect.succeed(alreadyDomain.value)
        // A value stored in its DOMAIN form, as a transform nested in a container
        // (or under `optional`) was before #133, comes back changed by the
        // unmarshaller: a `bigint` is written as `N` and read back as a JS
        // `number` (or a `bigint` only beyond the safe-integer range). Lift an
        // integer back to the `bigint` it was. Every other primitive domain form
        // (`number`, `string`, `boolean`, `Uint8Array`) reads back as itself and
        // is already accepted above.
        if (bigintDomain && typeof value === "number" && Number.isSafeInteger(value)) {
          const lifted = validateDomain(BigInt(value))
          if (lifted._tag === "Some") return Effect.succeed(lifted.value)
        }
        return Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
      }),
      encode: SchemaGetter.transformEffect((value: unknown) => {
        const wire = encodeDomain(value)
        if (wire._tag === "Some") return Effect.succeed(wire.value)
        // Already wire-shaped — round-trip it to itself rather than reject.
        const fromWire = decodeWire(value)
        if (fromWire._tag === "Some") {
          const reencoded = encodeDomain(fromWire.value)
          if (reencoded._tag === "Some") return Effect.succeed(reencoded.value)
        }
        return Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
      }),
    } as any),
  ) as unknown as Schema.Top
}

/** A plain `Schema.BigInt` (no transformation): stored as `N`, read back as a JS number. */
const isSelfBigInt = (schema: Schema.Top): boolean =>
  schema.ast.encoding === undefined && SchemaAST.isBigInt(schema.ast)

/** A safe integer, or a bigint the unmarshaller returned for an out-of-range `N`. */
const legacyBigInt = (value: unknown): bigint | undefined =>
  typeof value === "bigint"
    ? value
    : typeof value === "number" && Number.isSafeInteger(value)
      ? BigInt(value)
      : undefined

/**
 * A plain `Schema.BigInt` that also reads the form DynamoDB hands back (#133).
 * A `bigint` is marshalled as `N` and unmarshalled as a JS `number` (or as a
 * `bigint` beyond the safe-integer range), which `Schema.BigInt` rejects — so a
 * plain bigint field could be written but never read. Decode lifts a safe
 * integer back to the `bigint` it was; encode is the schema's own (identity).
 */
const buildBigIntLift = (schema: Schema.Top): Schema.Top => {
  const validate = Schema.decodeUnknownOption(schema as unknown as Schema.Codec<any>)
  const encode = Schema.encodeUnknownOption(schema as unknown as Schema.Codec<any>)
  return Schema.Any.pipe(
    Schema.decodeTo(
      schema as unknown as Schema.Codec<any>,
      {
        decode: SchemaGetter.transformEffect((value: unknown) => {
          const lifted = legacyBigInt(value)
          const valid = lifted === undefined ? validate(value) : validate(lifted)
          return valid._tag === "Some"
            ? Effect.succeed(valid.value)
            : Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
        }),
        encode: SchemaGetter.transformEffect((value: unknown) => {
          const wire = encode(value)
          return wire._tag === "Some"
            ? Effect.succeed(wire.value)
            : Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
        }),
      } as any,
    ),
  ) as unknown as Schema.Top
}

/**
 * An ENTITY transform field that also reads the domain-form values earlier
 * releases left behind (#133) — but only the forms no other wire value can be
 * mistaken for:
 *
 * - a `number` for a number-from-string transform (`NumberFromString`);
 * - a safe-integer `number` (or unmarshalled `bigint`) for a bigint-from-string;
 * - a marshalled `DateTime` map for a date transform (`DateTimeUtcFromString`).
 *
 * Path-based updates marshalled their value as given, so a `5` set on a
 * `NumberFromString` was stored as `N` and every later read failed with
 * "Expected string". A string is never accepted here other than through the
 * transform's own decode, and the encode is the transform's own with no
 * fallback, so what the transform writes is unchanged. Read schemas only.
 */
const buildLegacyReadTransform = (schema: Schema.Top): Schema.Top => {
  const typeAst = SchemaAST.toType(schema.ast)
  const typeSide = Schema.make<Schema.Top>(typeAst)
  const codec = schema as unknown as Schema.Codec<any>
  const decodeWire = Schema.decodeUnknownOption(codec)
  const validateDomain = Schema.decodeUnknownOption(typeSide as unknown as Schema.Codec<any>)
  const encodeWire = Schema.encodeUnknownOption(codec)
  const isDate = isDateTransform(schema)
  const numberDomain = SchemaAST.isNumber(typeAst)
  const bigintDomain = SchemaAST.isBigInt(typeAst)
  const legacy = (value: unknown): unknown => {
    if (isDate) return reviveMarshalledDateTime(value)
    if (numberDomain && typeof value === "number") return value
    if (bigintDomain) return legacyBigInt(value)
    return undefined
  }
  return Schema.Any.pipe(
    Schema.decodeTo(typeSide, {
      decode: SchemaGetter.transformEffect((value: unknown) => {
        const fromWire = decodeWire(value)
        if (fromWire._tag === "Some") return Effect.succeed(fromWire.value)
        const domain = legacy(value)
        if (domain !== undefined) {
          const valid = validateDomain(domain)
          if (valid._tag === "Some") return Effect.succeed(valid.value)
        }
        return Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
      }),
      encode: SchemaGetter.transformEffect((value: unknown) => {
        const wire = encodeWire(value)
        return wire._tag === "Some"
          ? Effect.succeed(wire.value)
          : Effect.fail(new SchemaIssue.InvalidType(schema.ast, value))
      }),
    } as any),
  ) as unknown as Schema.Top
}

/** A primitive kind a value can be stored as, for telling union members apart. */
type WireKind = "string" | "number"

/**
 * The primitive kinds a union member can be STORED as (#133). A self date is
 * stored as its configured storage kind; a plain `bigint` as `N`; anything
 * else as its encoded side's string / number forms. Objects, arrays, booleans
 * and null never collide with a date's primitive and contribute nothing.
 */
const memberWireKinds = (
  member: Schema.Top,
  options?: {
    /**
     * Also count the member's DOMAIN-side kinds. Aggregates (`tolerantTransforms`)
     * re-decode domain values on every `update`, so a `NumberFromString` member's
     * domain `5` competes with an epoch date for the same decode, just as a
     * `Number` member's stored `5` does on a read.
     */
    readonly domainSide?: boolean | undefined
  },
): ReadonlySet<WireKind> => {
  const kinds = new Set<WireKind>()
  const inner = optionalField(member)?.inner ?? member
  if (isSelfDateSchema(inner)) {
    const encoding = getEncoding(inner) ?? inferDefaultEncoding(inner)
    kinds.add(encoding?.storage === "string" || encoding === undefined ? "string" : "number")
    return kinds
  }
  const visit = (ast: SchemaAST.AST, seen: Set<SchemaAST.AST>) => {
    if (seen.has(ast)) return
    seen.add(ast)
    if (SchemaAST.isDeclaration(ast)) {
      // A self date nested in this member — `NullOr(DateTimeUtc)` inside an
      // outer union — is stored as its storage kind too.
      const nested = Schema.make<Schema.Top>(ast)
      if (isSelfDateSchema(nested)) {
        const encoding = getEncoding(nested) ?? inferDefaultEncoding(nested)
        kinds.add(encoding === undefined || encoding.storage === "string" ? "string" : "number")
      }
    } else if (SchemaAST.isAny(ast) || SchemaAST.isUnknown(ast)) {
      kinds.add("string")
      kinds.add("number")
    } else if (SchemaAST.isString(ast) || SchemaAST.isTemplateLiteral(ast)) {
      kinds.add("string")
    } else if (SchemaAST.isNumber(ast) || SchemaAST.isBigInt(ast)) {
      kinds.add("number")
    } else if (SchemaAST.isLiteral(ast)) {
      if (typeof ast.literal === "string") kinds.add("string")
      if (typeof ast.literal === "number" || typeof ast.literal === "bigint") kinds.add("number")
    } else if (SchemaAST.isEnum(ast)) {
      for (const [, value] of ast.enums) kinds.add(typeof value === "number" ? "number" : "string")
    } else if (SchemaAST.isUnion(ast)) {
      for (const type of ast.types) visit(type, seen)
    } else if (SchemaAST.isSuspend(ast)) {
      visit(ast.thunk(), seen)
    }
  }
  visit(SchemaAST.toEncoded(inner.ast), new Set())
  if (options?.domainSide) visit(SchemaAST.toType(inner.ast), new Set())
  return kinds
}

/**
 * True when the schema is a Schema.Class (a constructable function carrying
 * fields whose AST is a `Declaration`). The AST check matters: since Effect
 * 4.0.0-rc, `Schema.Struct(...)` is also a function, but its AST is `Objects`.
 */
const isClassSchema = (schema: Schema.Top): boolean =>
  typeof schema === "function" &&
  schemaFieldsOf(schema) !== undefined &&
  (schema.ast as { readonly _tag?: string })._tag === "Declaration"

/** The Struct AST a class decodes from — the last link of its encoding chain. */
const classStructAst = (schema: Schema.Top): SchemaAST.AST | undefined => {
  const encoding = schema.ast.encoding
  const last = encoding === undefined ? undefined : encoding[encoding.length - 1]
  return last !== undefined && SchemaAST.isObjects(last.to) ? last.to : undefined
}

/** True when the schema is `Schema.Array(...)` (AST tag `Arrays`). */
const isArraySchema = (schema: Schema.Top): boolean =>
  (schema.ast as { readonly _tag?: string })._tag === "Arrays"

/**
 * The element schema of a `Schema.Array(...)`. Prefers the runtime `.value`
 * accessor, but falls back to reconstructing from the AST (`rest[0]`) — schemas
 * recovered through optional-wrapper unwrapping carry the `Arrays` AST without a
 * runtime `.value`, so the accessor alone is not reliable. Returns `undefined`
 * if no element can be determined (defensive — never recurse into `undefined`).
 */
const arrayElementOf = (schema: Schema.Top): Schema.Top | undefined => {
  const direct = (schema as { readonly value?: Schema.Top }).value
  if (direct !== undefined) return direct
  const rest = (schema.ast as { readonly rest?: ReadonlyArray<unknown> }).rest
  const item = rest?.[0] as { readonly type?: Schema.Top["ast"] } | Schema.Top["ast"] | undefined
  const elementAst =
    (item as { readonly type?: Schema.Top["ast"] })?.type ?? (item as Schema.Top["ast"])
  return elementAst ? Schema.make<Schema.Top>(elementAst) : undefined
}

export interface OptionalField {
  /** The REAL inner schema X (class/struct/array/leaf) — `.fields` / `.value` /
   *  constructor intact, so the normal recursion can substitute and preserve it. */
  readonly inner: Schema.Top
  /** Re-apply the field's optionality to a substituted inner. */
  readonly rewrap: (substituted: Schema.Top) => Schema.Top
  /**
   * `Schema.optionalKey` over a union of several members: the whole union, with `inner` its first
   * member. See {@link writesFirstMemberOnly}.
   */
  readonly union?: Schema.Top
}

/**
 * Detect an optional struct field — `Schema.optional(X)` or `Schema.optionalKey(X)` —
 * and recover the REAL inner schema X plus a `rewrap` that re-applies the same
 * optionality after substitution. Recovery uses the runtime `.schema` / `.members`
 * accessors (which return real schemas with `.fields` / `.value` / constructor
 * intact), NOT AST reconstruction (which loses those). Returns `undefined` for
 * non-optional fields.
 *
 * @internal Also used by the aggregate runtime to see through a field's optionality.
 */
export const optionalField = (field: Schema.Top): OptionalField | undefined => {
  const ast = field.ast as {
    readonly _tag?: string
    readonly context?: { readonly isOptional?: boolean }
  }
  if (ast.context?.isOptional !== true) return undefined
  const value = (field as { readonly schema?: Schema.Top }).schema
  if (ast._tag === "Union") {
    // `Schema.optional(X)`: the value type is `UndefinedOr(X)`; `.members` exposes
    // the real X alongside the `Undefined` member.
    const members = (value as { readonly members?: ReadonlyArray<Schema.Top> } | undefined)?.members
    const defined = members?.filter(
      (m) => (m.ast as { readonly _tag?: string })._tag !== "Undefined",
    )
    const inner = defined?.[0]
    if (inner === undefined) return undefined
    return {
      inner,
      rewrap: (s) => Schema.optional(s as Schema.Codec<any>) as unknown as Schema.Top,
      ...(defined !== undefined && defined.length > 1 ? { union: value! } : {}),
    }
  }
  // `Schema.optionalKey(X)`: the value type is X directly (`.schema`).
  if (value === undefined) return undefined
  return {
    inner: value,
    rewrap: (s) => Schema.optionalKey(s as Schema.Codec<any>) as unknown as Schema.Top,
  }
}

/**
 * Options for {@link substituteSchemaDeep}, applied only at the IMMEDIATE
 * (top-level) fields of the passed schema — recursion into nested structures
 * proceeds without them.
 */
export interface DeepSubstitutionOptions {
  /**
   * Immediate field names to leave untouched (applied only at the top level).
   */
  readonly skipTopLevel?: ReadonlySet<string> | undefined
  /**
   * Re-point a `DynamoModel.ref` / aggregate-edge field at its target model
   * (applied only at the top level). The ref annotation is an opaque
   * `Declaration` that hides the target's fields, so the recursion can't see
   * into it; callers that know the edge graph supply the resolved target model
   * here. Return `undefined` to leave the field to the default handling.
   */
  readonly resolveRef?: ((name: string, field: Schema.Top) => Schema.Top | undefined) | undefined
  /**
   * The storage `DynamoModel.configure` gives immediate fields of the passed model (`storedAs` a
   * date schema), by name (applied only at the top level), as the model's own entity applies it
   * ({@link substituteSchemas}): a ref to that entity stores its item as the entity's read schema
   * encodes it (`refDataOf`), so it holds such a field in that storage ({@link configuredStorageOf}).
   */
  readonly configuredStorage?: Readonly<globalThis.Record<string, DynamoEncoding>> | undefined
  /**
   * Also substitute Pattern B transform date schemas (e.g.
   * `Schema.DateTimeUtcFromString`) with a TOLERANT date transform that accepts
   * the domain value too on decode. Propagated through the whole recursion.
   *
   * Use ONLY for decode-only schemas (the aggregate read/assemble + input
   * validation path), where the mutated state carries domain `DateTime` values
   * the transform's encoded-only decoder would reject. NEVER for schemas whose
   * `encode` produces the stored wire (entity record schemas) — a transform owns
   * its wire format and must not be overridden there.
   */
  readonly tolerantTransforms?: boolean | undefined
  /**
   * Set internally while substituting inside a `Union` member: date leaves get
   * a `strictWireKind` transform (see {@link buildDateTransform}). Propagated
   * through the rest of the recursion.
   */
  readonly strictWireKind?: boolean | undefined
  /**
   * Entity READ schemas only (#133): also accept the domain-form values earlier
   * releases stored on transform fields (see `buildLegacyReadTransform`), never
   * inside a union, where a lenient member could claim another member's value,
   * and lift an unmarshalled number back to a plain `Schema.BigInt` (see
   * `exactBigInts` for a union). Propagated through the recursion.
   */
  readonly legacyReads?: boolean | undefined
  /**
   * Set internally on a union's members for their first try: no read lift. A lifting member
   * accepts any safe integer, enough to claim a value another member holds as a number, so every
   * member gets its try as declared and only a value none of them takes is lifted. Propagated
   * through the recursion.
   */
  readonly exactBigInts?: boolean | undefined
  /**
   * A schema nothing is stored through: a read, or the validation of a value before it's encoded.
   * It can see beneath a decoding default on a container, whose runtime accessors the default hides
   * (see `decodingDefaultField`), without changing what's stored. Propagated through the recursion.
   */
  readonly decodeOnly?: boolean | undefined
  /**
   * Set internally on a union's members: the primitive kinds the OTHER members
   * are stored as — and, under `tolerantTransforms`, their domain kinds too,
   * since an aggregate re-decodes domain values on update. A self-date member
   * whose storage collides with one of them decodes only its canonical wire
   * form; an epoch storage that collides with a number kind is rejected at
   * `make()` with EDD-9058, since any integer is a canonical epoch (#133).
   * Applies to the immediate member, and to members of a union nested in it.
   */
  readonly collidingKinds?: ReadonlySet<WireKind> | undefined
  /**
   * A `DynamoModel.configure` storage override for a top-level UNION field,
   * applied to the union's (single) self-date member (#133). Passes through an
   * optional wrapper to the union; applies to that union's members only.
   */
  readonly unionDateOverride?: DynamoEncoding | undefined
  /** Set internally from `unionDateOverride` on the union's members. */
  readonly dateEncodingOverride?: DynamoEncoding | undefined
  /**
   * Set internally, beside a ref's `configuredStorage` on a READ schema: the date also reads the
   * form its own storage writes, which a ref copy holds where a path write put it there up to
   * 1.41.0 ({@link declaredStoragePlan}). Goes where the override goes.
   */
  readonly readsDeclaredStorage?: boolean | undefined
  /** The field path being substituted, for error messages. */
  readonly path?: ReadonlyArray<string> | undefined
  /**
   * WRITE schemas only (#133): keep the `.check()` refinements of the Arrays,
   * Structs and class Structs the substitution rebuilds. Rebuilding them with a
   * plain constructor dropped those checks, so a write breaking them was
   * accepted. Read schemas leave this off: a row written while the check was
   * not enforced must stay readable. Propagated through the recursion.
   */
  readonly enforceChecks?: boolean | undefined
  /**
   * READ schemas: a struct field whose stored side includes a value with no
   * stored form reads an absent attribute as that value (`absentStored`). `"only"`
   * substitutes nothing else, for a schema the entity derivation doesn't own (an
   * event, a snapshot state). Propagated through the recursion.
   */
  readonly absentReads?: boolean | "only" | undefined
  /**
   * An aggregate's mutated state only: a declaration also decodes from the form its plain
   * state holds it as (`Schema.toIso` gives a set as an array, an `Option` as a tagged
   * object), so a mutation can hand the state back. `create` input stays the declared type.
   * Propagated through the recursion.
   */
  readonly plainStateForms?: boolean | undefined
  /**
   * An aggregate's `create` input and mutated state: what a caller holds, so a tolerant leaf asks
   * its domain side first. Where a transformation has one type on both sides, a value asked as its
   * stored form first comes out transformed, stores what the caller gave and reads back changed,
   * and again on every update. A wire value still decodes where it can't be a domain one. A step
   * encoded as optional that isn't a default, such as `Schema.OptionFromOptional`, turns what's
   * stored into something else, and a caller holds that something else, so the step is gone round.
   * Propagated through the recursion.
   */
  readonly domainValues?: boolean | undefined
  /** See {@link writesFirstMemberOnly}. For this union alone, so not propagated. */
  readonly declaredOrder?: boolean | undefined
  /** See {@link writingTuplePositions}. Propagated through the recursion. */
  readonly undefinedPositionsOnly?: boolean | undefined
}

/** The options a nested schema inherits: everything but the per-position ones. */
const descend = (opts: DeepSubstitutionOptions | undefined): DeepSubstitutionOptions | undefined =>
  opts?.tolerantTransforms ||
  opts?.resolveRef ||
  opts?.strictWireKind ||
  opts?.legacyReads ||
  opts?.exactBigInts ||
  opts?.decodeOnly ||
  opts?.path ||
  opts?.enforceChecks ||
  opts?.absentReads ||
  opts?.plainStateForms ||
  opts?.domainValues ||
  opts?.undefinedPositionsOnly
    ? {
        ...(opts?.tolerantTransforms ? { tolerantTransforms: true } : {}),
        ...(opts?.resolveRef ? { resolveRef: opts.resolveRef } : {}),
        ...(opts?.strictWireKind ? { strictWireKind: true } : {}),
        ...(opts?.legacyReads ? { legacyReads: true } : {}),
        ...(opts?.exactBigInts ? { exactBigInts: true } : {}),
        ...(opts?.decodeOnly ? { decodeOnly: true } : {}),
        ...(opts?.path ? { path: opts.path } : {}),
        ...(opts?.enforceChecks ? { enforceChecks: true } : {}),
        ...(opts?.absentReads ? { absentReads: opts.absentReads } : {}),
        ...(opts?.plainStateForms ? { plainStateForms: true } : {}),
        ...(opts?.domainValues ? { domainValues: true } : {}),
        ...(opts?.undefinedPositionsOnly ? { undefinedPositionsOnly: true } : {}),
      }
    : undefined

/** Options for a struct / class field: the inherited ones, with the field on the path. */
const atField = (
  deeper: DeepSubstitutionOptions | undefined,
  opts: DeepSubstitutionOptions | undefined,
  name: string,
): DeepSubstitutionOptions => ({ ...deeper, path: [...(opts?.path ?? []), name] })

/**
 * A container the substitution walks only under `tolerantTransforms` (#133):
 * its child schemas, and how to rebuild it around substituted children.
 */
interface WalkedContainer {
  readonly children: ReadonlyArray<Schema.Top>
  readonly rebuild: (children: ReadonlyArray<Schema.Top>) => Schema.Top
  /** Children are alternatives (a `Union`), decoded member by member. */
  readonly isUnion: boolean
}

/**
 * The containers besides Struct / Class / Array that a value can nest a
 * transformed leaf in: `Union` (incl. `NullOr` and a non-field `UndefinedOr`),
 * `Record`, `Tuple`, `TupleWithRest` and `StructWithRest`. Each is rebuilt
 * through its own runtime accessors so its kind, union options and checks are
 * kept. `containsWireTransform` walks the same shapes.
 *
 * Walked in every mode. Without `tolerantTransforms` (entity derivation) the
 * walk substitutes only self-date and `Redacted` leaves, so an entity's
 * `NullOr(Schema.DateTimeUtc)` stores its wire form instead of a marshalled
 * `DateTime` (#133), while a Pattern B transform inside keeps owning its wire.
 */
const walkedContainer = (schema: Schema.Top): WalkedContainer | undefined => {
  const shape = containerShape(schema)
  if (shape === undefined) return undefined
  return { ...shape, rebuild: (children) => withMetadataOf(schema, shape.rebuild(children)) }
}

/**
 * Give a rebuilt container the original's node-level metadata — its
 * annotations, `.check()` refinements and context. Rebuilding through a
 * constructor (`Schema.Record(k, v)`, `Schema.TupleWithRest(…)`) produces a
 * fresh node without them, so a `.check(Schema.isMaxProperties(1))` on the
 * original was silently dropped and an invalid value accepted (#133).
 */
const withMetadataOf = (original: Schema.Top, rebuilt: Schema.Top): Schema.Top =>
  withAstMetadataOf(original.ast, rebuilt)

/** `withMetadataOf`, taking the metadata from an AST node. */
const withAstMetadataOf = (source: SchemaAST.AST, rebuilt: Schema.Top): Schema.Top => {
  const from = source as SchemaAST.AST & { readonly encodingChecks?: unknown }
  const to = rebuilt.ast as SchemaAST.AST & { readonly encodingChecks?: unknown }
  if (
    to.annotations === from.annotations &&
    to.checks === from.checks &&
    to.context === from.context &&
    to.encodingChecks === from.encodingChecks
  ) {
    return rebuilt
  }
  // AST nodes are immutable value objects: a shallow copy with the metadata
  // fields replaced is the same node shape the constructors produce.
  const ast = Object.assign(Object.create(Object.getPrototypeOf(to)), to, {
    annotations: from.annotations,
    checks: from.checks,
    context: from.context,
    encodingChecks: from.encodingChecks,
  }) as SchemaAST.AST
  return Schema.make<Schema.Top>(ast)
}

const containerShape = (schema: Schema.Top): WalkedContainer | undefined => {
  const s = schema as unknown as globalThis.Record<string, unknown>
  const ast = schema.ast
  // A container piped through its own transformation (`Record(…).pipe(decodeTo(…))`)
  // has an encoding chain tied to its ORIGINAL children; rebuilding it would
  // detach that chain, so it is left exactly as declared.
  if (ast.encoding !== undefined) return undefined
  const schemas = (value: unknown): ReadonlyArray<Schema.Top> | undefined =>
    Array.isArray(value) && value.every(isSchemaLike)
      ? (value as ReadonlyArray<Schema.Top>)
      : undefined
  if (SchemaAST.isUnion(ast)) {
    const members = schemas(s.members)
    if (members === undefined || typeof s.mapMembers !== "function") return undefined
    const union = schema as unknown as {
      mapMembers: (f: (m: unknown) => unknown, o: { unsafePreserveChecks: boolean }) => Schema.Top
    }
    return {
      children: members,
      rebuild: (subs) => union.mapMembers(() => subs, { unsafePreserveChecks: true }),
      isUnion: true,
    }
  }
  if (SchemaAST.isArrays(ast)) {
    const elements = schemas(s.elements)
    if (elements !== undefined && typeof s.mapElements === "function") {
      const tuple = schema as unknown as {
        mapElements: (
          f: (e: unknown) => unknown,
          o: { unsafePreserveChecks: boolean },
        ) => Schema.Top
      }
      return {
        children: elements,
        rebuild: (subs) => tuple.mapElements(() => subs, { unsafePreserveChecks: true }),
        isUnion: false,
      }
    }
    const rest = schemas(s.rest)
    if (isSchemaLike(s.schema) && rest !== undefined) {
      return {
        children: [s.schema, ...rest],
        rebuild: ([head, ...tail]) =>
          Schema.TupleWithRest(head as any, tail as any) as unknown as Schema.Top,
        isUnion: false,
      }
    }
    return undefined
  }
  if (SchemaAST.isObjects(ast)) {
    if (isSchemaLike(s.key) && isSchemaLike(s.value)) {
      const key = s.key
      return {
        children: [s.value],
        rebuild: ([value]) => Schema.Record(key as any, value as any) as unknown as Schema.Top,
        isUnion: false,
      }
    }
    const records = schemas(s.records)
    if (isSchemaLike(s.schema) && records !== undefined) {
      return {
        children: [s.schema, ...records],
        rebuild: ([head, ...tail]) =>
          Schema.StructWithRest(head as any, tail as any) as unknown as Schema.Top,
        isUnion: false,
      }
    }
  }
  return undefined
}

/** Whether a container holds nothing but dates, `Null` and `Undefined`: what an aggregate's date encoder takes. */
const holdsOnlyDates = (container: WalkedContainer): boolean =>
  container.children.every(
    (member) =>
      SchemaAST.isNull(member.ast) ||
      SchemaAST.isUndefined(member.ast) ||
      inferDefaultEncoding(member) !== undefined,
  )

/** Options for a tolerant container's children: a Union's members decode strictly by kind. */
const childOptions = (
  container: WalkedContainer,
  deeper: DeepSubstitutionOptions | undefined,
  index: number,
  opts: DeepSubstitutionOptions | undefined,
): DeepSubstitutionOptions | undefined => {
  if (!container.isUnion) return deeper
  // What the other members are stored as — plus, for a union nested inside
  // another (`Union([NullOr(DateTimeUtc), String])`), what the OUTER union's
  // other members are stored as: they compete for the same stored value.
  const collidingKinds = new Set<WireKind>(opts?.collidingKinds ?? [])
  container.children.forEach((member, i) => {
    if (i !== index) {
      const kinds = memberWireKinds(member, { domainSide: opts?.tolerantTransforms === true })
      for (const kind of kinds) collidingKinds.add(kind)
    }
  })
  return {
    ...deeper,
    strictWireKind: true,
    collidingKinds,
    ...(opts?.unionDateOverride ? { dateEncodingOverride: opts.unionDateOverride } : {}),
    ...(opts?.unionDateOverride && opts.readsDeclaredStorage ? { readsDeclaredStorage: true } : {}),
  }
}

/** The options an optional wrapper hands its inner schema: it is transparent. */
/**
 * A field whose LAST encoding step makes the encoded key optional while the
 * type side stays required — `Schema.withDecodingDefault(…)` /
 * `withDecodingDefaultKey(…)`, or any `optional(…).pipe(decodeTo(…))`. Its
 * inner schema (the field without that step) is what substitution works on;
 * `rewrap` re-applies the same step on top of the substitute, so the default
 * survives (#133). Without it a self-date / transform leaf was replaced
 * wholesale and the read schema lost the default — a stored item without the
 * key failed to decode.
 */
const decodingDefaultField = (
  field: Schema.Top,
):
  | {
      readonly inner: Schema.Top
      /** The field beneath the step with its runtime accessors, without a check added after the step. */
      readonly declared: Schema.Top
      readonly rewrap: (s: Schema.Top, decode?: unknown) => Schema.Top
      /** The step is a default, with what the field stores on both sides of it. */
      readonly defaults: boolean
      /** The default stands for `undefined` too, as `Schema.withDecodingDefault`'s does. */
      readonly withUndefined: boolean
      /**
       * The step is a transformation: it goes onto another type, as `Schema.OptionFromOptional` does,
       * or what it comes from has an encoding of its own, which `rewrap` wouldn't keep.
       */
      readonly transforms: boolean
    }
  | undefined => {
  const ast = field.ast
  const encoding = ast.encoding
  if (encoding === undefined || encoding.length === 0) return undefined
  if ((ast.context as { readonly isOptional?: boolean } | undefined)?.isOptional === true) {
    return undefined
  }
  const last = encoding[encoding.length - 1]!
  const lastTo = last.to as SchemaAST.AST & {
    readonly context?: { readonly isOptional?: boolean }
  }
  if (lastTo.context?.isOptional !== true) return undefined
  const transformation = last.transformation as unknown as {
    readonly _tag?: string
    readonly decode: unknown
    readonly encode: unknown
  }
  if (transformation._tag !== "Transformation") return undefined
  // The same node without its last encoding step (what Effect's internal
  // `replaceEncoding` does: a shallow copy carrying the shorter chain).
  const innerAst = Object.assign(Object.create(Object.getPrototypeOf(ast)), ast, {
    encoding: encoding.length === 1 ? undefined : encoding.slice(0, -1),
  }) as SchemaAST.AST
  const inner = Schema.make<Schema.Top>(innerAst)
  const withUndefined =
    SchemaAST.isUnion(lastTo) && lastTo.types.some((t) => SchemaAST.isUndefined(t))
  return {
    inner,
    transforms: !isDecodingDefault(ast, lastTo) || lastTo.encoding !== undefined,
    declared: (field as { readonly to?: Schema.Top }).to ?? inner,
    defaults: isDecodingDefault(SchemaAST.toEncoded(innerAst), lastTo),
    withUndefined,
    rewrap: (substitute, decode = transformation.decode) => {
      const encodedSide = Schema.toEncoded(substitute as Schema.Codec<any>)
      const optionalEncoded = withUndefined
        ? Schema.optional(encodedSide)
        : Schema.optionalKey(encodedSide)
      return optionalEncoded.pipe(
        Schema.decodeTo(
          substitute as Schema.Codec<any>,
          {
            decode,
            encode: transformation.encode,
          } as any,
        ),
      ) as unknown as Schema.Top
    },
  }
}

/**
 * Whether this substitution is an entity's or an aggregate's write, which substitutes only the first
 * member of a union under `Schema.optionalKey`. Later members are written as declared, so what's
 * stored for them stays what every release has stored: a `Schema.DateTimeUtc` declared after a
 * `Schema.String` is Effect's internal form, and one declared before it is a string. Changing that
 * would change a stored format. A read takes each member's forms in the order they're declared
 * (`declaredOrder`), as a later date isn't stored as the text a string before it takes, and a number
 * under a first `Schema.BigInt` was written as that bigint.
 */
const writesFirstMemberOnly = (opts: DeepSubstitutionOptions | undefined): boolean =>
  !opts?.decodeOnly && !opts?.absentReads && !opts?.undefinedPositionsOnly

const throughOptional = (
  opts: DeepSubstitutionOptions | undefined,
): DeepSubstitutionOptions | undefined => {
  const deeper = descend(opts)
  return opts?.unionDateOverride || opts?.collidingKinds || opts?.dateEncodingOverride
    ? {
        ...deeper,
        ...(opts.unionDateOverride ? { unionDateOverride: opts.unionDateOverride } : {}),
        ...(opts.collidingKinds ? { collidingKinds: opts.collidingKinds } : {}),
        ...(opts.dateEncodingOverride ? { dateEncodingOverride: opts.dateEncodingOverride } : {}),
        ...(opts.readsDeclaredStorage ? { readsDeclaredStorage: true } : {}),
      }
    : deeper
}

/**
 * The substitute for a self-date leaf: its own (or the configured) storage,
 * adjusted for a union whose other members collide with it (#133).
 */
const selfDatePlan = (
  schema: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
): { readonly encoding: DynamoEncoding; readonly canonicalOnly: boolean } | undefined => {
  const own = getEncoding(schema) ?? inferDefaultEncoding(schema)
  if (!own) return undefined
  const encoding: DynamoEncoding = opts?.dateEncodingOverride
    ? { storage: opts.dateEncodingOverride.storage, domain: own.domain }
    : own
  const colliding = opts?.collidingKinds
  let canonicalOnly = false
  if (colliding !== undefined) {
    // An epoch number is indistinguishable from a number member's value — any
    // integer is a canonical epoch — so no stored number could be read back
    // reliably. Refused at make() time (EDD-9058) rather than guessed.
    if (encoding.storage !== "string" && colliding.has("number")) {
      const field = opts?.path?.length ? opts.path.join(".") : "(unnamed)"
      const reason = opts?.tolerantTransforms
        ? `next to a member that is stored as a number or decodes to one (aggregates ` +
          `re-decode domain values on update, so a NumberFromString / BigIntFromString ` +
          `member collides too). A number could belong to either member`
        : `next to a member that is also stored as a number. A stored number could ` +
          `belong to either member`
      throw new Error(
        `[EDD-9058] Field "${field}" is a union whose date member is stored as an epoch ` +
          `number (${encoding.storage}), ${reason}, so it cannot be read back reliably. ` +
          `Store the date as a string (DynamoModel.DateString — the default for a self ` +
          `date), or remove the numeric member from the union.`,
      )
    }
    canonicalOnly = colliding.has(encoding.storage === "string" ? "string" : "number")
  }
  return { encoding, canonicalOnly }
}

/**
 * Under `readsDeclaredStorage`, in a union: the plan of the storage the date declares, where the
 * override reads another kind of value (see `readsDeclaredStorage`). Out of a union the override's
 * transform reads a value by its kind already, text as ISO text and a number in its own scale.
 */
const declaredStoragePlan = (
  schema: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
): ReturnType<typeof selfDatePlan> => {
  if (!opts?.readsDeclaredStorage || !opts.strictWireKind || !opts.dateEncodingOverride) {
    return undefined
  }
  const own = getEncoding(schema) ?? inferDefaultEncoding(schema)
  const text = (encoding: DynamoEncoding) => encoding.storage === "string"
  if (own === undefined || text(own) === text(opts.dateEncodingOverride)) return undefined
  try {
    return selfDatePlan(schema, { ...opts, dateEncodingOverride: undefined })
  } catch {
    // An epoch beside a number member (EDD-9058) is refused where it's the storage, not here.
    return undefined
  }
}

const selfDateSubstitute = (
  schema: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
): Schema.Top => {
  const plan = selfDatePlan(schema, opts)
  if (plan === undefined) return schema
  const substitute = buildDateTransform(plan.encoding, {
    strictWireKind: opts?.strictWireKind,
    canonicalOnly: plan.canonicalOnly,
  })
  // Encodes as the override, and reads either form, as an aggregate's union member does.
  const declared = declaredStoragePlan(schema, opts)
  return declared === undefined
    ? substitute
    : (Schema.Union([
        substitute as Schema.Codec<any>,
        buildDateTransform(declared.encoding, {
          strictWireKind: true,
          canonicalOnly: declared.canonicalOnly,
        }) as Schema.Codec<any>,
      ]) as unknown as Schema.Top)
}

/**
 * Whether a union member is a self date that claims only its canonical form
 * (see `selfDatePlan`). Such a member is decoded FIRST: its canonical spelling
 * is the one value it and a colliding member could both take, and that value
 * is what the library writes for a date — so it is read as the date whatever
 * the declared member order. Encoding is unaffected: a date and a string /
 * number are told apart by their Type side, which no reordering changes.
 */
const isCanonicalDateMember = (
  member: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
): boolean => {
  const inner = optionalField(member)?.inner ?? member
  if (isSelfDateSchema(inner)) {
    return (
      selfDatePlan(inner, opts)?.canonicalOnly === true ||
      declaredStoragePlan(inner, opts)?.canonicalOnly === true
    )
  }
  // A nested union holding such a member (`NullOr(DateTimeUtc)` next to a
  // `String`) is decoded first for the same reason.
  const container = walkedContainer(inner)
  if (container === undefined || !container.isUnion) return false
  return container.children.some((child, index) =>
    isCanonicalDateMember(child, childOptions(container, descend(opts), index, opts)),
  )
}

/** Whether a leaf gets a read-leniency substitute (see `legacyReads`). */
const needsLegacyRead = (schema: Schema.Top, opts: DeepSubstitutionOptions | undefined) =>
  opts?.legacyReads === true &&
  opts.strictWireKind !== true &&
  schemaFieldsOf(schema) === undefined &&
  !isArraySchema(schema) &&
  (isDateTransform(schema) || numericTypeWithStringEncoding(schema))

/** Whether a plain `Schema.BigInt` gets the read lift here (aggregate decode, entity reads). */
const liftsBigInts = (opts: DeepSubstitutionOptions | undefined) =>
  (opts?.tolerantTransforms === true || opts?.legacyReads === true) && opts.exactBigInts !== true

const needsBigIntLift = (schema: Schema.Top, opts: DeepSubstitutionOptions | undefined) =>
  liftsBigInts(opts) && isSelfBigInt(schema)

/** Whether what's stored for a schema the substitution can't walk holds a plain `Schema.BigInt`. */
const holdsUnwalkedBigInt = (schema: Schema.Top): boolean =>
  holdsPlainBigint(SchemaAST.toEncoded(schema.ast))

/**
 * A list with a step on it that an entity writes through as declared, which is one with no date or
 * redacted value on its type side. A read walking that type side would skip the step, so it finds what
 * the step makes where the stored form is. This reads it as declared, with its bigints lifted, unless
 * nothing's in the way of the walk: a list stored as one, with no plain bigint on either side.
 */
const readsListAsDeclared = (schema: Schema.Top, opts: DeepSubstitutionOptions | undefined) => {
  if (opts?.legacyReads !== true) return false
  const { ast } = schema
  if (!SchemaAST.isArrays(ast) || ast.encoding === undefined) return false
  if (needsDeepSubstitution(schema, undefined)) return false
  return (
    storedList(ast.encoding[ast.encoding.length - 1]!.to) === undefined ||
    holdsUnwalkedBigInt(schema) ||
    [...ast.elements, ...ast.rest].some((element) => holdsPlainBigint(SchemaAST.toEncoded(element)))
  )
}

/** Whether what's stored for a schema the substitution can't walk can leave a value out. */
const holdsUnwalkedAbsent = (schema: Schema.Top): boolean =>
  holdsAbsentValue(SchemaAST.toEncoded(schema.ast))

/** Whether a plain `Schema.BigInt` is anywhere the substitution walks. */
const holdsBigInt = (schema: Schema.Top): boolean => {
  const opt = optionalField(schema)
  const defaulted = decodingDefaultField(schema)
  // What's beneath a step that isn't a default isn't what's stored, and it isn't walked.
  if (defaulted !== undefined && !defaulted.defaults) return holdsUnwalkedBigInt(schema)
  const inner = opt?.union ?? opt?.inner ?? defaulted?.declared
  if (inner !== undefined) return holdsBigInt(inner)
  if (isSelfBigInt(schema)) return true
  const container = walkedContainer(schema)
  if (container !== undefined) return container.children.some((child) => holdsBigInt(child))
  if (isArraySchema(schema)) {
    const element = arrayElementOf(schema)
    return element !== undefined && holdsBigInt(element)
  }
  const fields = schemaFieldsOf(schema)
  return fields === undefined
    ? holdsUnwalkedBigInt(schema)
    : Object.values(fields).some((field) => holdsBigInt(field))
}

/**
 * What the substitution works on beneath a decoding default (see `decodeOnly`). A read doesn't
 * enforce a check on what it rebuilds (see `enforceChecks`), and a write schema keeps the one added
 * after the default.
 */
const beneathDefault = (
  schema: Schema.Top,
  defaulted: NonNullable<ReturnType<typeof decodingDefaultField>>,
  opts: DeepSubstitutionOptions | undefined,
): Schema.Top =>
  (opts?.legacyReads || opts?.decodeOnly) &&
  !(opts.enforceChecks && defaulted.declared.ast.checks !== schema.ast.checks)
    ? defaulted.declared
    : defaulted.inner

/**
 * What an absent field reads as, for what asks for the domain value first (see `domainValues`), and
 * anything else as it was given. A decoding default is in the stored form and a step makes something
 * else of nothing at all, so absent is read through the field as declared, and what's beneath gets
 * the domain value that gives.
 */
const absentAsDeclared = (schema: Schema.Top, withUndefined: boolean) => {
  const read = Schema.decodeUnknownEffect(
    Schema.Struct({ field: schema }) as unknown as Schema.Codec<{ readonly field: unknown }>,
  )
  return SchemaGetter.transformOptionalEffect((input: Option.Option<unknown>) =>
    Option.isSome(input) && !(withUndefined && input.value === undefined)
      ? Effect.succeed(input)
      : read({}).pipe(
          Effect.map(({ field }) => Option.some(field)),
          Effect.mapError((error) => error.issue),
        ),
  )
}

/** `undefined`, or a set holding nothing once `undefined` is removed: no attribute is stored. */
const storesNothing = (value: unknown): boolean =>
  value === undefined ||
  (value instanceof Set && [...value].every((element) => element === undefined))

/**
 * The annotation marking a field {@link protoAbsent} made: an annotation, not identity, since the
 * modules reading it may be loaded twice (the package's source beside its build).
 */
const PROTO_ABSENT: unique symbol = Symbol.for("@effect-dynamodb/schema/ProtoAbsent")

/** Whether `field` is one {@link protoAbsent} made. */
export const isProtoAbsent = (field: unknown): boolean => {
  const ast = (field as { readonly ast?: SchemaAST.AST } | null | undefined)?.ast
  return (ast?.annotations as Record<symbol, unknown> | undefined)?.[PROTO_ABSENT] === true
}

/**
 * A field named `__proto__`, stored under that name, of a struct the library builds over the
 * model's (#239). 1.40.0 built each such struct by assignment, `fields[name] = schema`, and
 * assigning `__proto__` set the map's prototype instead: the field wasn't in the struct. A payload
 * leaving it out was taken, and one giving it lost the value, which the parser dropped. Here a
 * payload leaving it out, or giving a value that stores nothing (`undefined`, a `None` encoded as
 * `undefined`, a set holding nothing), is read as 1.40.0 read it: the field isn't in what the struct
 * makes. A value that stores something is refused (`EDD-9165`), since no write can store it and no
 * read can return it. What a value stores is what the field, as declared, makes of it on the way to
 * storage: encoded, or as it is where it's already in its stored form.
 */
const protoAbsent = (field: Schema.Top): Schema.Top => {
  const holder = Schema.Struct({ v: field } as Schema.Struct.Fields) as unknown as Schema.Codec<
    { readonly v?: unknown },
    { readonly v?: unknown }
  >
  const decode = Schema.decodeUnknownExit(holder)
  const encode = Schema.encodeUnknownExit(holder)
  /** The value as stored, `undefined` for none; the value as given where the field takes neither. */
  const stored = (value: unknown, encoding: boolean): unknown => {
    const asIs = () =>
      Exit.isSuccess(decode({ v: value })) ? Exit.succeed({ v: value }) : undefined
    const toStored = () => {
      const encoded = encode({ v: value })
      return Exit.isSuccess(encoded) ? encoded : undefined
    }
    for (const attempt of encoding ? [toStored, asIs] : [asIs, toStored]) {
      const held = attempt()
      if (held !== undefined && Exit.isSuccess(held)) {
        return Object.hasOwn(held.value, "v") ? held.value.v : undefined
      }
    }
    return value
  }
  const judge = (encoding: boolean) =>
    SchemaGetter.transformOptionalEffect<unknown, unknown>((given) =>
      Option.isNone(given) ||
      storesNothing(given.value) ||
      storesNothing(stored(given.value, encoding))
        ? Effect.succeed(Option.none())
        : Effect.fail(
            new SchemaIssue.InvalidValue(
              { message: `${PROTO_ENTRY} [EDD-9165]` },
              Option.some(given.value),
            ),
          ),
    )
  return Schema.optionalKey(
    Schema.Unknown.pipe(
      Schema.decodeTo(
        Schema.Unknown.annotate({ [PROTO_ABSENT]: true } as Schema.Annotations.Annotations),
        new SchemaTransformation.Transformation(judge(false), judge(true)),
      ),
    ),
  ) as unknown as Schema.Top
}

/**
 * `field` under `name`: where that's `__proto__`, stored so, the field {@link protoAbsent} makes of
 * the one the model `declared`, whose encoding is the stored form.
 */
const fieldNamed = (
  name: string,
  field: Schema.Top,
  declared: Schema.Top,
  storedAsProto = true,
): Schema.Top =>
  name === "__proto__" && storedAsProto && !isProtoAbsent(field) ? protoAbsent(declared) : field

/**
 * The field, reading an absent attribute as the value it stands for (`absentStored`), which is what
 * its `declared` schema says, if the field is that schema read some other way.
 */
const readingAbsent = (field: Schema.Top, declared: Schema.Top = field): Schema.Top => {
  const reading = absentStored(declared)
  if (reading === undefined) return field
  // A stored value is read as `field` alone (`ReadsAbsentAs`): the default runs where none is.
  return field
    .pipe(
      Schema.withDecodingDefaultKey(Effect.succeed(reading.stored)) as (
        self: Schema.Top,
      ) => Schema.Top,
    )
    .annotate({ [ReadsAbsentAs]: field.ast })
}

/** Whether a struct field anywhere in the schema reads an absent attribute as a value. */
const holdsAbsentRead = (schema: Schema.Top): boolean => {
  const opt = optionalField(schema)
  if (opt !== undefined) return holdsAbsentRead(opt.union ?? opt.inner)
  const defaulted = decodingDefaultField(schema)
  if (defaulted !== undefined) return holdsAbsentRead(defaulted.inner)
  const container = walkedContainer(schema)
  if (container !== undefined) return container.children.some((child) => holdsAbsentRead(child))
  if (isArraySchema(schema)) {
    const element = arrayElementOf(schema)
    return element !== undefined && holdsAbsentRead(element)
  }
  const fields = schemaFieldsOf(schema)
  return (
    fields !== undefined &&
    Object.values(fields).some(
      (field) => absentStored(field) !== undefined || holdsAbsentRead(field),
    )
  )
}

/** Whether a tuple has a fixed position that can hold `undefined`. */
const hasUndefinedPosition = (schema: Schema.Top): boolean =>
  SchemaAST.isArrays(schema.ast) && schema.ast.elements.some((element) => holdsUndefined(element))

/** Whether a tuple with a position that can hold `undefined` is anywhere in the schema. */
const holdsUndefinedPosition = (schema: Schema.Top): boolean => {
  const opt = optionalField(schema)
  const inner = opt?.union ?? opt?.inner ?? decodingDefaultField(schema)?.inner
  if (inner !== undefined) return holdsUndefinedPosition(inner)
  if (hasUndefinedPosition(schema)) return true
  const container = walkedContainer(schema)
  if (container !== undefined) {
    return container.children.some((child) => holdsUndefinedPosition(child))
  }
  if (isArraySchema(schema)) {
    const element = arrayElementOf(schema)
    return element !== undefined && holdsUndefinedPosition(element)
  }
  const fields = schemaFieldsOf(schema)
  return (
    fields !== undefined && Object.values(fields).some((field) => holdsUndefinedPosition(field))
  )
}

/**
 * Marshalling drops `undefined` from a list, closing it up. In a tuple that moves
 * the values after it to other positions, or leaves a required position empty, so
 * the row reads back wrong or not at all. Only a last optional position can go, and
 * a position in a tuple's rest, which is a list.
 */
const refusingUndefinedPositions = (tuple: Schema.Top): Schema.Top => {
  const optional = (tuple.ast as SchemaAST.Arrays).elements.map((element) =>
    SchemaAST.isOptional(element),
  )
  return (
    tuple as Schema.Top & { readonly check: (...checks: ReadonlyArray<unknown>) => Schema.Top }
  ).check(
    Schema.makeFilter((values: ReadonlyArray<unknown>) => {
      const position = values.findIndex(
        (value, index) =>
          value === undefined &&
          index < optional.length &&
          (optional[index] !== true ||
            values.slice(index + 1).some((later) => later !== undefined)),
      )
      return (
        position === -1 ||
        `Position ${position} holds undefined, and a list can't keep an empty position: ` +
          "the values after it would move, or the row couldn't be read"
      )
    }),
  )
}

/** Whether a substitution of this schema refuses what its tuple positions can't keep. */
const refusesUndefinedPositions = (
  schema: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
): boolean =>
  opts?.enforceChecks === true && opts.absentReads !== "only" && hasUndefinedPosition(schema)

/**
 * Recursively determine whether a schema contains — at any depth reachable
 * through nested `Schema.Struct` / `Schema.Class` / `Schema.Array` — a leaf that
 * needs substitution for wire round-tripping (a self-date schema or a
 * `RedactedFromValue`). Returns false for schemas that don't, so
 * {@link substituteSchemaDeep} can return them unchanged (zero structural churn).
 *
 * Optional wrappers are unwrapped to their real inner schema, and the walk
 * enters `Union` members, `Record` values and `Tuple` elements too (see
 * `walkedContainer`).
 */
const needsDeepSubstitution = (schema: Schema.Top, opts?: DeepSubstitutionOptions): boolean => {
  if (schema == null || (schema as { readonly ast?: unknown }).ast == null) return false
  // A ref held as less than its class (`refHeldTarget`) is another schema than the field it
  // re-points, whatever its leaves.
  if (heldStructs.has(schema)) return true
  if (opts?.undefinedPositionsOnly) return holdsUndefinedPosition(schema)
  if (opts?.absentReads === "only") return holdsAbsentRead(schema)
  if (opts?.absentReads && holdsUnwalkedAbsent(schema)) return true
  if (opts?.enforceChecks && hasUndefinedPosition(schema)) return true
  // `tolerantTransforms` AND `resolveRef` propagate through the recursion;
  // `skipTopLevel` names top-level fields only, so it is dropped below.
  //
  // `resolveRef` has to descend: a `DynamoModel.ref` field nested INSIDE an edge
  // model is annotated, and `Schema.annotate` drops a `Schema.Class`'s `.fields`,
  // so the walker cannot see through it and the target's own transformed fields
  // keep their strict schemas. Only callers that pass `resolveRef` are affected
  // — the entity derivation passes none (#116).
  const deeper = descend(opts)
  // Optional wrapper FIRST — unwrap to the REAL inner before the leaf / array /
  // struct checks. `optionalKey(X)` is a bare AST (Declaration/Arrays) with an
  // `isOptional` context, so the leaf detectors (which resolve through to the
  // type constructor) would otherwise treat `optionalKey(date)` as a plain
  // required date and drop the optionality; and an `optionalKey(Array)` wrapper
  // has the `Arrays` AST but no runtime `.value`.
  const opt = optionalField(schema)
  if (opt !== undefined) {
    const read = writesFirstMemberOnly(opts) ? undefined : opt.union
    return needsDeepSubstitution(read ?? opt.inner, throughOptional(opts))
  }
  const defaulted = decodingDefaultField(schema)
  if (defaulted !== undefined) {
    return defaulted.defaults
      ? (defaulted.transforms && liftsBigInts(opts) && holdsUnwalkedBigInt(schema)) ||
          needsDeepSubstitution(beneathDefault(schema, defaulted, opts), opts)
      : opts?.domainValues === true || (liftsBigInts(opts) && holdsUnwalkedBigInt(schema))
  }
  if (readsListAsDeclared(schema, opts)) return readingUnwalked(schema, opts) !== schema
  if (isSelfDateSchema(schema)) return true
  if (opts?.tolerantTransforms && isDateTransform(schema)) return true
  if (tryGetRedactedInner(schema) !== undefined) return true
  // Any other leaf transform, tolerant mode only — same reason as the date
  // case: after a mutation the field may hold either form (#116).
  if (opts?.tolerantTransforms && isTolerantLeaf(schema)) return true
  if (needsLegacyRead(schema, opts) || needsBigIntLift(schema, opts)) return true
  if (opts?.plainStateForms && holdsPlainForm(schema.ast)) return true
  if (opts?.tolerantTransforms && holdsTransformation(schema.ast)) return true
  const container = walkedContainer(schema)
  if (container !== undefined) {
    return container.children.some((child, index) =>
      needsDeepSubstitution(child, childOptions(container, deeper, index, opts)),
    )
  }
  if (isArraySchema(schema)) {
    const element = arrayElementOf(schema)
    return element !== undefined && needsDeepSubstitution(element, deeper)
  }
  const fields = schemaFieldsOf(schema)
  if (fields) {
    return Object.entries(fields).some(([name, field]) => {
      if (opts?.skipTopLevel?.has(name)) return false
      // Re-point ref edge fields at their target; optionality is handled when the
      // field itself is recursed into (optional unwrap at the entry above).
      const refTarget = opts?.resolveRef?.(name, field)
      return needsDeepSubstitution(refTarget ?? field, deeper)
    })
  }
  return liftsBigInts(opts) && holdsUnwalkedBigInt(schema)
}

/**
 * Whether a mutation can hold this as something else: a declaration of Effect's or a custom one,
 * as opposed to a `Schema.Class`, whose AST is a declaration encoded as its struct and whose
 * fields are walked, or whatever a `Schema.suspend` holds, which isn't. See `plainStateForms`.
 */
const holdsPlainForm = (ast: SchemaAST.AST): boolean =>
  (ast._tag === "Declaration" && ast.encoding === undefined) || SchemaAST.isSuspend(ast)

/**
 * A declaration with a transformation inside, such as `Schema.Option(Schema.DateFromString)`, or a
 * `Schema.suspend` with one. The tolerant substitution doesn't reach under either, so an aggregate's
 * `create` would be handed the domain value and refuse it.
 */
const holdsTransformation = (ast: SchemaAST.AST): boolean =>
  SchemaAST.isSuspend(ast)
    ? astContainsWireTransform(ast, new Set(), false)
    : holdsPlainForm(ast) &&
      (ast as SchemaAST.Declaration).typeParameters.some(
        (parameter) => SchemaAST.toType(parameter) !== parameter,
      )

/** A declaration or a suspended schema, or its domain value. See `holdsTransformation`. */
const acceptingDomainForm = (declaration: Schema.Top): Schema.Top =>
  Schema.Union([declaration, Schema.toType(declaration)] as never) as unknown as Schema.Top

/**
 * A declaration, or either of what a mutation can hand back for it: the domain value it was
 * given, or the form its plain state holds it as. See `plainStateForms`.
 */
const acceptingPlainForm = (declaration: Schema.Top): Schema.Top =>
  buildTolerantTransform(declaration, true, declaration)

/**
 * A type side whose own check takes what isn't the transform's: `Unknown`, `Any`, or a declaration
 * with nothing inside it (`Schema.declare`, `Schema.instanceOf`).
 */
const takesAnything = (type: SchemaAST.AST): boolean =>
  SchemaAST.isUnknown(type) ||
  SchemaAST.isAny(type) ||
  (SchemaAST.isDeclaration(type) && type.typeParameters.length === 0)

/** A tolerant substitute for a field a read makes `read` of. See `buildTolerantTransform`. */
const tolerantLeaf = (
  schema: Schema.Top,
  opts: DeepSubstitutionOptions | undefined,
  read: Schema.Top,
): Schema.Top => {
  const type = SchemaAST.toType(schema.ast)
  return buildTolerantTransform(
    read,
    opts?.domainValues,
    // A plain state holds a declaration in another form. With nothing beneath the domain side that
    // is one, the plain form is the domain value: asked first, a value read wire first (an
    // aggregate's `decompose` input) would be taken as the domain value instead.
    opts?.plainStateForms && holdsDeclaration(type, new Set())
      ? Schema.make<Schema.Top>(type)
      : undefined,
    // 1.39.0's own leaves (stored as a string or a number) take a domain value as they did.
    !isLeafEncodingTransform(schema) && takesAnything(type),
  )
}

/** Whether a declaration (a set, an `Option`, a class, a date) is anywhere in `ast`. */
const holdsDeclaration = (ast: SchemaAST.AST, seen: Set<SchemaAST.AST>): boolean => {
  if (seen.has(ast)) return false
  seen.add(ast)
  if (SchemaAST.isDeclaration(ast)) return true
  const walk = (child: SchemaAST.AST) => holdsDeclaration(child, seen)
  if (SchemaAST.isArrays(ast)) return ast.elements.some(walk) || ast.rest.some(walk)
  if (SchemaAST.isObjects(ast)) {
    return (
      ast.propertySignatures.some((ps) => walk(ps.type)) ||
      ast.indexSignatures.some((is) => walk(is.type))
    )
  }
  if (SchemaAST.isUnion(ast)) return ast.types.some(walk)
  if (SchemaAST.isSuspend(ast)) return walk(ast.thunk())
  return false
}

/**
 * Recursively substitute self-date and `RedactedFromValue` leaves wherever they
 * appear — including inside nested `Schema.Class` / `Schema.Struct` / `Schema.Array`
 * fields (e.g. a `DynamoModel.ref` target or an aggregate edge model that carries
 * a `Schema.DateTimeUtc` field). Nested `Schema.Class` identity is preserved:
 * the substituted struct decodes to a real class instance via
 * `Schema.instanceOf` + prototype attach, so consumers still receive instances.
 *
 * Returns the input schema unchanged when nothing needs substituting, so callers
 * that don't have nested transform fields see no structural change at all.
 *
 * See {@link DeepSubstitutionOptions} for `skipTopLevel` / `resolveRef`.
 *
 * @internal
 */
export const substituteSchemaDeep = (
  schema: Schema.Top,
  opts?: DeepSubstitutionOptions,
): Schema.Top => {
  if (!needsDeepSubstitution(schema, opts)) return schema

  // `tolerantTransforms`, `resolveRef`, `strictWireKind` and `legacyReads`
  // propagate through the recursion (`descend`); `skipTopLevel` and the
  // per-position union options do not.
  //
  // `resolveRef` has to descend: a `DynamoModel.ref` field nested INSIDE an edge
  // model is annotated, and `Schema.annotate` drops a `Schema.Class`'s `.fields`,
  // so the walker cannot see through it and the target's own transformed fields
  // keep their strict schemas. Only callers that pass `resolveRef` are affected
  // — the entity derivation passes none (#116).
  const deeper = descend(opts)

  // Optional wrapper FIRST — unwrap to the REAL inner, substitute it, then
  // re-apply the same optionality. Handled BEFORE the leaf / array / struct
  // checks: the leaf detectors resolve through an `optionalKey` wrapper and would
  // otherwise replace `optionalKey(date)` with a plain required transform (losing
  // the optional key), and an optional array's `.value` lives only on the inner.
  const opt = optionalField(schema)
  if (opt !== undefined) {
    const first = substituteSchemaDeep(opt.inner, throughOptional(opts))
    if (opt.union === undefined) return opt.rewrap(first)
    if (!writesFirstMemberOnly(opts)) {
      const read = substituteSchemaDeep(opt.union, {
        ...throughOptional(opts),
        declaredOrder: true,
      })
      // A member of a union reads only its own forms, so it doesn't claim a later member's rows.
      // The first was read as the whole field until now, and a row it took then still reads.
      return opt.rewrap(
        first === opt.inner
          ? read
          : (Schema.Union([
              read as Schema.Codec<any>,
              first as Schema.Codec<any>,
            ]) as unknown as Schema.Top),
      )
    }
    // Over the members themselves, so `optionalField` still tells them apart in what's built here.
    return Schema.optionalKey(
      (opt.union as unknown as Schema.Union<ReadonlyArray<Schema.Top>>).mapMembers(
        (members) => [
          ...members.map((member) => (member === opt.inner ? first : member)),
          Schema.Undefined,
        ],
        { unsafePreserveChecks: true },
      ) as unknown as Schema.Codec<any>,
    ) as unknown as Schema.Top
  }
  // A decoding default (or any optional-encoded step) on top: substitute the
  // field beneath it and keep the step, so a missing key still defaults (#133).
  // What the walk below can't enter: a declaration, a `Schema.suspend` or a transformation. What a
  // read makes of a plain bigint or an absent value in one, it makes of it where it sits.
  const unwalked = () => readingUnwalked(schema, opts)

  const defaulted = decodingDefaultField(schema)
  if (defaulted !== undefined) {
    const domainValues = opts?.domainValues === true
    // A step that isn't a default turns what's stored into something else. What's beneath it isn't
    // what's stored, so it stays as declared, and a caller, who holds that something else, goes round it.
    if (!defaulted.defaults) {
      return domainValues
        ? defaulted.rewrap(
            tolerantLeaf(schema, opts, schema),
            absentAsDeclared(schema, defaulted.withUndefined),
          )
        : unwalked()
    }
    if (defaulted.transforms && !domainValues && unwalked() !== schema) return unwalked()
    const beneath = substituteSchemaDeep(beneathDefault(schema, defaulted, opts), opts)
    return defaulted.rewrap(
      refusesUndefinedPositions(defaulted.inner, opts)
        ? refusingUndefinedPositions(beneath)
        : beneath,
      domainValues ? absentAsDeclared(schema, defaulted.withUndefined) : undefined,
    )
  }

  if (readsListAsDeclared(schema, opts)) return unwalked()
  // Leaf: self-date schema → tolerant bidirectional date transform.
  if (isSelfDateSchema(schema)) return selfDateSubstitute(schema, opts)
  // Leaf: Pattern B transform date schema (only under `tolerantTransforms`) →
  // tolerant date transform whose decode also accepts the already-domain value.
  // Inside a union it keeps the transform's OWN decode instead: the union picks
  // a member by what each one accepts, and the generic date transform accepts
  // more (any epoch number, any parseable string) than the user's transform —
  // enough to claim a value that belongs to a later member (#133).
  if (opts?.tolerantTransforms && isDateTransform(schema)) {
    if (opts.strictWireKind) return buildTolerantTransform(unwalked(), opts.domainValues)
    const encoding = getEncoding(schema) ?? inferDefaultEncoding(schema)
    if (encoding) return buildDateTransform(encoding)
  }
  // Leaf: RedactedFromValue → tolerant Redacted transform.
  const redactedInner = tryGetRedactedInner(schema)
  if (redactedInner !== undefined) return buildRedactedSubstitute(schema, redactedInner)

  // Leaf: any OTHER encoding transform (only under `tolerantTransforms`) →
  // a substitute whose decode accepts the wire form and the domain form. Placed
  // after the date and Redacted branches so those keep their dedicated
  // substitutes, and before the array / struct recursion so containers are
  // still walked rather than swallowed (#116).
  if (opts?.tolerantTransforms && isTolerantLeaf(schema)) {
    return tolerantLeaf(schema, opts, unwalked())
  }
  // Leaf: read leniency for legacy domain-form values (entity read schemas) and
  // the plain-bigint lift (#133).
  if (needsLegacyRead(schema, opts)) return buildLegacyReadTransform(unwalked())
  if (needsBigIntLift(schema, opts)) return buildBigIntLift(schema)
  if (opts?.plainStateForms && holdsPlainForm(schema.ast)) return acceptingPlainForm(unwalked())
  if (holdsTransformation(schema.ast)) {
    return opts?.domainValues
      ? buildTolerantTransform(unwalked(), true)
      : acceptingDomainForm(unwalked())
  }

  // Union / Record / Tuple / *WithRest: substitute every child and rebuild the
  // same container kind, metadata included (#133). Without `tolerantTransforms`
  // (entity derivation) only self-date / Redacted leaves inside are
  // substituted, exactly as for a Struct or an Array. A union's members each
  // learn which primitive kinds the others are stored as (`childOptions`).
  const container = walkedContainer(schema)
  if (container !== undefined) {
    const children = container.children.map((child, index) => {
      const childOpts = childOptions(container, deeper, index, opts)
      const member = substituteSchemaDeep(child, childOpts)
      // An aggregate stores a first date transform in its date encoding, not its own wire form, and
      // a date in a union of nothing else but null in the form its domain infers, whatever it declares.
      const stored = !opts?.tolerantTransforms
        ? undefined
        : holdsOnlyDates(container)
          ? inferDefaultEncoding(child)
          : index === 0 && opts.declaredOrder
            ? (getEncoding(child) ?? inferDefaultEncoding(child))
            : undefined
      return {
        child,
        childOpts,
        substituted:
          stored === undefined
            ? member
            : (Schema.Union([
                member as Schema.Codec<any>,
                buildDateTransform(stored, {
                  strictWireKind: true,
                  canonicalOnly: true,
                }) as Schema.Codec<any>,
              ]) as unknown as Schema.Top),
        first:
          container.isUnion &&
          opts?.absentReads !== "only" &&
          !opts?.declaredOrder &&
          isCanonicalDateMember(child, childOpts),
      }
    })
    const ordered = [...children.filter((c) => c.first), ...children.filter((c) => !c.first)]
    const lifting = (c: (typeof ordered)[number]) =>
      container.isUnion &&
      liftsBigInts(c.childOpts) &&
      holdsBigInt(c.child) &&
      !(opts?.declaredOrder && c === ordered[0])
    const lenient = ordered.filter(
      (c) =>
        (opts?.absentReads && holdsAbsentRead(c.child)) ||
        (opts?.absentReads === true && holdsUnwalkedAbsent(c.child)) ||
        lifting(c) ||
        (opts?.plainStateForms && holdsPlainForm(c.child.ast)),
    )
    if (!container.isUnion || lenient.length === 0) {
      const rebuilt = container.rebuild(ordered.map((c) => c.substituted))
      return refusesUndefinedPositions(schema, opts) ? refusingUndefinedPositions(rebuilt) : rebuilt
    }
    // A member reading an absent attribute as a value, or lifting a number to a
    // bigint, accepts more than it declares, enough to claim a row of a later
    // member. So every member gets its try as declared first, and only a row none
    // of them takes reads absent or is lifted. A `oneOf` union refuses a value two
    // members accept: it stays as declared, with only the lift tried outside it,
    // since a row as a bigint is what it was written as.
    const declared = (c: (typeof ordered)[number]) =>
      opts?.absentReads === "only"
        ? c.child
        : substituteSchemaDeep(c.child, {
            ...c.childOpts,
            absentReads: undefined,
            plainStateForms: undefined,
            exactBigInts: true,
          })
    if ((schema.ast as SchemaAST.Union).options?.mode === "oneOf") {
      const exact = container.rebuild(ordered.map((c) => declared(c)))
      const lifted = ordered.filter((c) => lifting(c)).map((c) => c.substituted)
      return lifted.length === 0
        ? exact
        : withMetadataOf(schema, Schema.Union([exact, ...lifted] as never) as unknown as Schema.Top)
    }
    return container.rebuild([
      ...ordered.map((c) => (lenient.includes(c) ? declared(c) : c.substituted)),
      ...lenient.map((c) => c.substituted),
    ])
  }

  // Array: substitute the element schema.
  if (isArraySchema(schema)) {
    const element = arrayElementOf(schema)
    if (element === undefined) return schema
    const rebuilt = Schema.Array(
      substituteSchemaDeep(element, deeper) as Schema.Codec<any>,
    ) as unknown as Schema.Top
    return opts?.enforceChecks ? withMetadataOf(schema, rebuilt) : rebuilt
  }

  // Struct / Class: substitute each field, recursing into nested structures.
  // Ref edge fields are re-pointed via `resolveRef` (re-applying any optionality);
  // every other field recurses (optional wrappers are unwrapped at the entry above).
  // The inner is always a REAL schema, so nested classes/arrays/leaves are handled
  // by the recursion (and class instance identity is preserved).
  const fields = schemaFieldsOf(schema)
  if (fields) {
    // A field named `__proto__` is one 1.40.0's rebuilt struct didn't hold (`protoAbsent`).
    const subFields: SchemaFields = {}
    for (const [name, field] of Object.entries(fields)) {
      if (opts?.skipTopLevel?.has(name) === true) {
        setOwn(subFields, name, fieldNamed(name, field, field))
        continue
      }
      const refTarget = opts?.resolveRef?.(name, field)
      if (refTarget !== undefined) {
        const fieldOpt = optionalField(field)
        const sub = substituteSchemaDeep(refTarget, atField(deeper, opts, name))
        setOwn(subFields, name, fieldNamed(name, fieldOpt ? fieldOpt.rewrap(sub) : sub, field))
      } else {
        const sub = substituteSchemaDeep(
          field,
          withConfiguredStorage(
            atField(deeper, opts, name),
            name,
            field,
            ownValue(opts?.configuredStorage, name),
          ),
        )
        setOwn(
          subFields,
          name,
          name === "__proto__"
            ? fieldNamed(name, sub, field)
            : opts?.absentReads
              ? readingAbsent(sub)
              : sub,
        )
      }
    }
    const plainStruct = Schema.Struct(subFields as Schema.Struct.Fields) as unknown as Schema.Top
    if (!isClassSchema(schema)) {
      return opts?.enforceChecks ? withMetadataOf(schema, plainStruct) : plainStruct
    }
    // A class built over a checked Struct (`Schema.Class("C")(Struct(…).check(f))`)
    // keeps that check on the Struct its encoding leads to.
    const classStruct = classStructAst(schema)
    const subStruct = (opts?.enforceChecks && classStruct !== undefined
      ? withAstMetadataOf(classStruct, plainStruct)
      : plainStruct) as unknown as Schema.Struct<Schema.Struct.Fields>
    // Preserve the class instance: decode the substituted struct to the original
    // class via prototype attach (no constructor re-validation, no field re-decode).
    const ctor = schema as unknown as new (input: unknown) => unknown
    return subStruct.pipe(
      Schema.decodeTo(
        Schema.instanceOf(ctor) as unknown as Schema.Codec<any>,
        {
          decode: SchemaGetter.transform((value: unknown) =>
            Object.assign(Object.create((ctor as { prototype: object }).prototype), value),
          ),
          encode: SchemaGetter.transform((instance: unknown) => ({ ...(instance as object) })),
        } as any,
      ),
    ) as unknown as Schema.Top
  }

  return unwalked()
}

/**
 * What a declaration is, when its stored form is a marshalled `DateTime`. A `.check()`, a brand or an
 * annotation keeps the declaration, so it's still the date it was; a transformation over one isn't,
 * and the date beneath it is reached through its encoding.
 */
const isMarshalledDate = (ast: SchemaAST.AST): boolean => {
  if (!SchemaAST.isDeclaration(ast) || ast.encoding !== undefined) return false
  const domain = matchDateRepresentation(ast.annotations)?.domain
  return domain === "DateTime.Utc" || domain === "DateTime.Zoned"
}

/**
 * A stored date, rebuilt, before it meets its declaration. Only a value carrying the marker a
 * marshalled date carries is touched: the declaration's guard takes the current one, so what it
 * accepts doesn't change, and the one Effect's betas and early rcs wrote is the one form added. Any
 * other value goes on to the declaration as it was, which refuses it or takes it as it always has, so
 * a union picks the member it picked before.
 */
const rebuildingMarshalledDate = {
  decode: SchemaGetter.transform((value: unknown): unknown =>
    typeof value === "object" &&
    value !== null &&
    (DATE_MARKER in value || BETA_DATE_MARKER in value)
      ? (reviveMarshalledDateTime(value) ?? value)
      : value,
  ),
  encode: SchemaGetter.passthrough<unknown>(),
}

/** A plain `Schema.BigInt`, checked or branded or not, stored as `N`: a transformation is reached through. */
const isMarshalledBigInt = (ast: SchemaAST.AST): boolean =>
  SchemaAST.isBigInt(ast) && ast.encoding === undefined

/**
 * A stored bigint, lifted, before it meets its declaration: a number that's a safe integer becomes
 * the bigint it was, and a bigint the unmarshaller returned stays one. Any other value goes on to the
 * declaration as it was. The walker refuses a union in which another member takes the number
 * (`EDD-9125`), so a number reaching this is a number no member takes.
 */
const liftingMarshalledBigInt = {
  decode: SchemaGetter.transform((value: unknown): unknown => legacyBigInt(value) ?? value),
  encode: SchemaGetter.passthrough<unknown>(),
}

const astWith = <A extends SchemaAST.AST>(ast: A, changes: Partial<A>): A =>
  Object.assign(Object.create(Object.getPrototypeOf(ast)), ast, changes)

/**
 * The same node with its children through `f`, or the node itself when none of them changed. Walks
 * the AST, not the schema's accessors, so it reaches every position: a `Schema.annotate` drops a
 * class's `.fields`, and a declaration's type parameters and a transformation's encoded side have no
 * accessor at all. A suspended schema is walked when it's forced, as a recursive one has no end.
 */
const withChildren = (
  ast: SchemaAST.AST,
  f: (child: SchemaAST.AST) => SchemaAST.AST,
  absentValues = false,
) => {
  switch (ast._tag) {
    case "Declaration": {
      const typeParameters = SchemaAST.mapOrSame(ast.typeParameters, (parameter) =>
        absentValues ? readingAbsentParameter(parameter, f(parameter)) : f(parameter),
      )
      return typeParameters === ast.typeParameters ? ast : astWith(ast, { typeParameters })
    }
    case "Arrays": {
      const elements = SchemaAST.mapOrSame(ast.elements, f)
      const rest = SchemaAST.mapOrSame(ast.rest, f)
      return elements === ast.elements && rest === ast.rest ? ast : astWith(ast, { elements, rest })
    }
    case "Objects": {
      const propertySignatures = SchemaAST.mapOrSame(ast.propertySignatures, (property) => {
        const read = f(property.type)
        const type = absentValues
          ? readingAbsent(Schema.make<Schema.Top>(read), Schema.make<Schema.Top>(property.type)).ast
          : read
        return type === property.type
          ? property
          : new SchemaAST.PropertySignature(property.name, type)
      })
      const indexSignatures = SchemaAST.mapOrSame(ast.indexSignatures, (index) => {
        const type = f(index.type)
        return type === index.type ? index : new SchemaAST.IndexSignature(index.parameter, type)
      })
      return propertySignatures === ast.propertySignatures &&
        indexSignatures === ast.indexSignatures
        ? ast
        : astWith(ast, { propertySignatures, indexSignatures })
    }
    case "Union": {
      const types = SchemaAST.mapOrSame(ast.types, f)
      return types === ast.types ? ast : astWith(ast, { types })
    }
    case "Suspend":
      return astWith(ast, { thunk: () => f(ast.thunk()) })
    default:
      return ast
  }
}

/**
 * A declaration's value, read as what it stands for when it's absent. The marshaller leaves an empty
 * set out of what it stores, and an `Option`, a `Result`, an `Exit` or a `Cause` holding one then has
 * no value at all. `undefined` needs nothing: it's what an absent one reads as already.
 */
const readingAbsentParameter = (declared: SchemaAST.AST, read: SchemaAST.AST): SchemaAST.AST => {
  const stored = absentStored(Schema.make<Schema.Top>(declared))?.stored
  if (stored === undefined) return read
  return Schema.Unknown.pipe(
    Schema.decodeTo(
      Schema.make<Schema.Top>(read) as never,
      {
        decode: SchemaGetter.transform((value: unknown): unknown =>
          value === undefined ? stored : value,
        ),
        encode: SchemaGetter.passthrough<unknown>(),
      } as never,
    ),
  ).ast
}

/**
 * A union where a member takes more than it declares, by reading an absent value, is what
 * `substituteSchemaDeep` makes one it can walk: enough to claim a row of a later member, so the
 * members as declared get their try first, and only a row none of them takes reads absent. Each side
 * stays whole, so a `oneOf` one still refuses a value two members take.
 */
const tryingDeclaredFirst = (
  ast: SchemaAST.Union,
  read: SchemaAST.Union,
  declared: (ast: SchemaAST.AST) => SchemaAST.AST,
): SchemaAST.AST =>
  ast.types.some((member) => holdsAbsentValue(SchemaAST.toEncoded(member)))
    ? astWith(ast, {
        types: [astWith(ast, { types: ast.types.map((member) => declared(member)) }), read],
        options: { ...ast.options, mode: "anyOf" },
      })
    : read

/**
 * A schema with what `rebuildOf` names, wherever it sits, rebuilt before it meets its node, and with
 * `absentValues` a value the marshaller left out read as what it stands for.
 */
const readingStored = (
  rebuildOf: (ast: SchemaAST.AST) => object | undefined,
  absentValues = false,
) => {
  const declared = absentValues ? readingStored(rebuildOf) : undefined
  const memo = new WeakMap<SchemaAST.AST, SchemaAST.AST>()
  const reading = (ast: SchemaAST.AST): SchemaAST.AST => {
    const known = memo.get(ast)
    if (known !== undefined) return known
    let read: SchemaAST.AST
    const rebuild = rebuildOf(ast)
    if (rebuild !== undefined) {
      const stored = ast.context?.isOptional ? Schema.optionalKey(Schema.Unknown) : Schema.Unknown
      read = stored.pipe(
        Schema.decodeTo(Schema.make<Schema.Top>(ast) as never, rebuild as never),
      ).ast
    } else {
      // What's stored is the encoded side: a type side holds what its transformation made, and
      // nothing was left out of that.
      const stored = declared !== undefined && ast.encoding === undefined
      read = stored ? withChildren(ast, reading, true) : withChildren(ast, declared ?? reading)
      if (stored && SchemaAST.isUnion(ast)) {
        read = tryingDeclaredFirst(ast, read as SchemaAST.Union, declared)
      }
      const encoding =
        ast.encoding &&
        (SchemaAST.mapOrSame(ast.encoding, (link) => {
          const to = reading(link.to)
          return to === link.to ? link : new SchemaAST.Link(to, link.transformation)
        }) as SchemaAST.Encoding)
      if (encoding !== ast.encoding) read = astWith(read, { encoding })
    }
    memo.set(ast, read)
    return read
  }
  return reading
}

/**
 * Every marshalled date and bigint in a schema, wherever it sits, read back as a real one, and every
 * value the marshaller left out as what it stands for.
 */
const readingMarshalled = readingStored(
  (ast) =>
    isMarshalledDate(ast)
      ? rebuildingMarshalledDate
      : isMarshalledBigInt(ast)
        ? liftingMarshalledBigInt
        : undefined,
  true,
)

const bigIntRebuild = (ast: SchemaAST.AST) =>
  isMarshalledBigInt(ast) ? liftingMarshalledBigInt : undefined
const liftingBigInts = readingStored(bigIntRebuild)
const liftingBigIntsAndAbsent = readingStored(bigIntRebuild, true)

/**
 * A schema the substitution can't walk, read as the walk reads what it can reach: every plain bigint
 * in it as one, and on a read that wants them, every absent value as what it stands for.
 */
const readingUnwalked = (schema: Schema.Top, opts: DeepSubstitutionOptions | undefined) => {
  if (opts?.absentReads === true && holdsUnwalkedAbsent(schema)) {
    return Schema.make<Schema.Top>(liftingBigIntsAndAbsent(schema.ast))
  }
  return liftsBigInts(opts) && holdsUnwalkedBigInt(schema)
    ? Schema.make<Schema.Top>(liftingBigInts(schema.ast))
    : schema
}

/**
 * The read schema of a value the library stores but doesn't derive: an event, its metadata, a
 * snapshot state, an outbox effect. Every read of one goes through it, so anything a stream's read
 * does differently from its declaration belongs here. Differently, as it stands, in four ways:
 *
 * - An absent attribute reads as the value it stands for (`absentStored`).
 * - A `Schema.DateTimeUtc` or `Schema.DateTimeZoned` comes back as a real date. Nothing substitutes
 *   these on write, so one is stored as the map the marshaller makes of it, and Effect's guard only
 *   looks for the marker and the tag, which that map has. Left to the guard, it reads back as a plain
 *   object that passes `DateTime.isDateTime` and isn't one: `Equal` is false, and on a named zone
 *   `DateTime.getPart` throws.
 * - A `Schema.BigInt` comes back as a bigint. The marshaller stores one as a number, and the
 *   unmarshaller returns a safe integer as a number, so without this only the values past 2^53 read.
 * - Each of Effect's other look-alike declarations (a `BigDecimal`, a `Duration`, a zone, an address,
 *   ...) comes back as a real instance, where the read takes one (`readingInstances`).
 *
 * Returned as it came when none applies to it.
 *
 * @internal
 */
export const readingStreamValues = (schema: Schema.Top): Schema.Top => {
  const absent = substituteSchemaDeep(schema, { absentReads: "only", enforceChecks: true })
  const read = readingMarshalled(absent.ast)
  return readingInstances(read === absent.ast ? absent : Schema.make<Schema.Top>(read))
}

/**
 * A schema the library stores but doesn't derive, refusing a tuple position holding
 * `undefined` that a stored list can't keep, and otherwise exactly as declared.
 * Unchanged when no tuple of it can hold one.
 *
 * @internal
 */
export const writingTuplePositions = (schema: Schema.Top): Schema.Top =>
  substituteSchemaDeep(schema, { undefinedPositionsOnly: true, enforceChecks: true })

/**
 * Substitute model fields with bidirectional transforms where needed:
 *
 *  - Self date schemas with an effective encoding (annotation or override)
 *    → tolerant date transform that accepts either wire form (string/number)
 *    or domain form (DateTime / Date) on decode, and always produces the
 *    configured wire primitive on encode.
 *  - `Schema.RedactedFromValue(inner)` fields → tolerant Redacted transform
 *    that accepts either form on decode and unwraps to wire primitive on
 *    encode (Effect v4's `RedactedFromValue` forbids encoding by default;
 *    our substitution makes the round-trip work for storage).
 *
 * Existing transform schemas (other than `RedactedFromValue`) are passed
 * through unchanged — the user-declared transform IS the wire format.
 *
 * Nested `Schema.Class` / `Schema.Struct` / `Schema.Array` fields (e.g. a
 * `DynamoModel.ref` target) are substituted RECURSIVELY via
 * {@link substituteSchemaDeep}: any self-date or `RedactedFromValue` leaf inside
 * them is converted so it round-trips through DynamoDB, while the nested class
 * instance identity is preserved. Fields with no such leaf pass through
 * untouched. (Nested fields reached only through `Schema.optional` / union
 * members are left as declared — see `substituteSchemaDeep`.)
 *
 * @internal
 */
export const substituteSchemas = (
  modelFields: SchemaFields,
  fieldEncodings: globalThis.Record<string, DynamoEncoding>,
  options?: {
    /** Build READ schemas: see `DeepSubstitutionOptions.legacyReads`. */
    readonly legacyReads?: boolean | undefined
    /** Build WRITE schemas: see `DeepSubstitutionOptions.enforceChecks`. */
    readonly enforceChecks?: boolean | undefined
    /** Build READ schemas: see `DeepSubstitutionOptions.absentReads`. */
    readonly absentReads?: boolean | undefined
    /**
     * A field named `__proto__` is stored under another attribute (`DynamoModel.configure`'s
     * `field`), so it's held as declared. Otherwise it's held as 1.40.0's map, built by
     * assignment, held it: not at all (`protoAbsent`).
     */
    readonly protoRenamed?: boolean | undefined
  },
): SchemaFields => {
  const out: SchemaFields = {}
  const storedAsProto = options?.protoRenamed !== true
  const deep: DeepSubstitutionOptions = {
    ...(options?.legacyReads ? { legacyReads: true } : {}),
    ...(options?.enforceChecks ? { enforceChecks: true } : {}),
    ...(options?.absentReads ? { absentReads: true } : {}),
  }
  for (const [name, schema] of Object.entries(modelFields)) {
    // 1. Self-date substitution. Pattern A: user declared `Schema.DateTimeUtc`
    //    and chose a wire format via annotation. We substitute with the
    //    tolerant date transform so the encode pipeline produces the right
    //    wire primitive.
    if (isSelfDateSchema(schema)) {
      const enc = ownValue(fieldEncodings, name)
      if (enc) {
        setOwn(out, name, fieldNamed(name, buildDateTransform(enc), schema, storedAsProto))
        continue
      }
    }
    // …also beneath a decoding default, which is kept on top (#133).
    const defaulted = decodingDefaultField(schema)
    if (defaulted !== undefined && isSelfDateSchema(defaulted.inner)) {
      const enc = ownValue(fieldEncodings, name)
      if (enc) {
        setOwn(
          out,
          name,
          fieldNamed(name, defaulted.rewrap(buildDateTransform(enc)), schema, storedAsProto),
        )
        continue
      }
    }
    // 2. RedactedFromValue substitution. Effect v4's `RedactedFromValue`
    //    forbids encoding by design; substitute with a tolerant Redacted
    //    transform so the round-trip works for storage.
    const redactedInner = tryGetRedactedInner(schema)
    if (redactedInner !== undefined) {
      setOwn(
        out,
        name,
        fieldNamed(name, buildRedactedSubstitute(schema, redactedInner), schema, storedAsProto),
      )
      continue
    }
    // 3. Default: recurse for nested substitution. Pattern B transforms
    //    (DynamoModel.*, Schema.DateTimeUtcFromString, Schema.NumberFromString, …)
    //    own their wire format and pass through; primitives pass through. But a
    //    nested Schema.Class / Schema.Struct / Schema.Array field (e.g. a
    //    `DynamoModel.ref` target) may itself carry a self-date or Redacted leaf
    //    — `substituteSchemaDeep` substitutes those while preserving class
    //    identity, and returns the schema unchanged when nothing nested needs it.
    //    A configured storage override on a UNION field (`NullOr(DateTimeUtc)`)
    //    is applied to the union's self-date member (#133).
    const unionOverride = unionDateOverride(name, schema, ownValue(fieldEncodings, name))
    setOwn(
      out,
      name,
      fieldNamed(
        name,
        substituteSchemaDeep(schema, {
          ...deep,
          path: [name],
          ...(unionOverride === undefined ? {} : { unionDateOverride: unionOverride }),
        }),
        schema,
        storedAsProto,
      ),
    )
  }
  if (options?.absentReads) {
    for (const [name, field] of Object.entries(out)) {
      if (!isProtoAbsent(field)) setOwn(out, name, readingAbsent(field))
    }
  }
  return out
}

/**
 * The storage a `DynamoModel.configure(..., { field: { storedAs } })` override
 * gives a top-level UNION field's date member, or `undefined` when the field is
 * not a union with a self-date member (#133).
 *
 * The override names one storage for the field; a union holding several self
 * dates gives it no single member to apply to, so that is refused at
 * `Entity.make()` rather than guessed (EDD-9057).
 */
const unionDateOverride = (
  name: string,
  schema: Schema.Top,
  encoding: DynamoEncoding | undefined,
): DynamoEncoding | undefined => {
  if (encoding === undefined) return undefined
  const inner = optionalField(schema)?.inner ?? schema
  if (!SchemaAST.isUnion(inner.ast)) return undefined
  const members = (inner as unknown as { readonly members?: ReadonlyArray<Schema.Top> }).members
  const dateMembers = (members ?? []).filter((member) =>
    isSelfDateSchema(optionalField(member)?.inner ?? member),
  )
  if (dateMembers.length === 0) return undefined
  if (dateMembers.length > 1) {
    throw new Error(
      `[EDD-9057] Field "${name}" is a union with ${dateMembers.length} date members, and its ` +
        `configured storage override (DynamoModel.configure … storedAs) cannot say which one it ` +
        `applies to. Annotate the intended member directly with ` +
        `\`.pipe(DynamoModel.storedAs(...))\` and drop the field-level override.`,
    )
  }
  return encoding
}

/**
 * @internal The storage `DynamoModel.configure` gives a model's fields (`storedAs` a date schema),
 * by name, or `undefined` for a model with none. What a ref to the model's entity holds such a
 * field in (`DeepSubstitutionOptions.configuredStorage`).
 */
export const configuredStorageOf = (
  model: unknown,
): Readonly<globalThis.Record<string, DynamoEncoding>> | undefined => {
  if (!isConfiguredModel(model)) return undefined
  const storage: globalThis.Record<string, DynamoEncoding> = {}
  for (const [name, attribute] of Object.entries(model.attributes)) {
    if (attribute.encoding !== undefined) setOwn(storage, name, attribute.encoding)
  }
  return Object.keys(storage).length === 0 ? undefined : storage
}

/**
 * A field's substitution options with the storage `encoding` its model's `DynamoModel.configure`
 * gives it, where its entity applies that storage ({@link substituteSchemas} decides by the same
 * tests): a date (a `Schema.optionalKey` one too, or one beneath a decoding default), or a union's
 * date member. Elsewhere, and without one, `options` as given. A read (`legacyReads`) also takes
 * the form the date's own storage writes (`readsDeclaredStorage`).
 */
const withConfiguredStorage = (
  options: DeepSubstitutionOptions,
  name: string,
  field: Schema.Top,
  encoding: DynamoEncoding | undefined,
): DeepSubstitutionOptions => {
  if (encoding === undefined) return options
  const reads = options.legacyReads ? { readsDeclaredStorage: true } : {}
  const defaulted = decodingDefaultField(field)
  if (isSelfDateSchema(field) || (defaulted !== undefined && isSelfDateSchema(defaulted.inner))) {
    return { ...options, dateEncodingOverride: encoding, ...reads }
  }
  const union = unionDateOverride(name, field, encoding)
  return union === undefined ? options : { ...options, unionDateOverride: union, ...reads }
}

/**
 * Validate that no model field combines a transform schema with a storage
 * override. The two configuration paths are mutually exclusive: either declare
 * a self schema (`Schema.DateTimeUtc`) and let the annotation drive storage,
 * OR declare a transform and own the wire format yourself — not both.
 *
 * Two override sources are checked:
 *
 *  1. `ConfiguredModel.storedAs` (configured attributes) — surfaces the
 *     override via `configuredAttributes[name].encoding`.
 *
 *  2. `DynamoModel.storedAs(...)` modifier piped onto the field schema —
 *     adds a `DynamoEncoding` annotation directly to the AST. We detect this
 *     by checking whether the field-level annotation disagrees with the
 *     transform's actual wire format (the `inferDefaultEncoding` of the
 *     transform). For an unmodified transform (e.g. `DynamoModel.DateString`
 *     with a matching ISO-string annotation), the two agree and the field is
 *     accepted.
 *
 * Throws at `Entity.make()` time if the conflict is detected.
 *
 * @internal
 */
export const validateNoTransformOverride = (
  modelFields: SchemaFields,
  configuredAttributes: ConfiguredAttributeEncodings,
): void => {
  const conflictMessage = (name: string) =>
    `[effect-dynamodb] Field "${name}": cannot apply DynamoEncoding storage override to a transform schema. ` +
    `Either declare a self schema (Schema.DateTimeUtc) and let the annotation drive storage, OR declare a transform and own the wire format — not both.`

  for (const [name, schema] of Object.entries(modelFields)) {
    if (!isDateTransform(schema)) continue

    // 1. ConfiguredModel.storedAs override?
    const configOverride = ownValue(configuredAttributes, name)?.encoding
    if (configOverride !== undefined) {
      throw new Error(conflictMessage(name))
    }

    // 2. DynamoModel.storedAs() modifier on the schema itself?
    if (storedAsOverTransform(schema)) {
      throw new Error(conflictMessage(name))
    }
  }
}

/**
 * Whether a date transform schema carries a `DynamoModel.storedAs(...)` annotation of the other wire
 * kind: one {@link validateNoTransformOverride} refuses. The modifier applies a `DynamoEncoding`
 * annotation to the AST; it conflicts when its storage disagrees with the transform's actual wire
 * format (resolved via `transformWireKind`, which walks the typed `Base.encoding` chain to its leaf).
 * Granularity: "string" vs "number" wire forms; epochMs vs epochSeconds can't be told apart at this
 * layer. The string-vs-number mismatch covers the most common breaking case. Such a field stores the
 * transform's form, so a value in the annotation's form can't be read back from it.
 *
 * @internal Also read by `Entity.make`: a `Schema.optional` date of this kind isn't a stamp.
 */
export const storedAsOverTransform = (schema: Schema.Top): boolean => {
  if (!isDateTransform(schema)) return false
  const annotated = getEncoding(schema)
  if (annotated === undefined) return false
  const transformWire = transformWireKind(schema)
  if (transformWire === undefined) return false
  return transformWire !== (annotated.storage === "string" ? "string" : "number")
}

/**
 * Read the wire form ("string" or "number") that a transform schema actually
 * encodes to, by walking the encoding chain. Returns undefined when the chain
 * is missing or the leaf isn't a String / Number node.
 *
 * Delegates to {@link SchemaAccessors.transformWireKind}, which uses the typed
 * `Base.encoding` property and `SchemaAST.isString`/`isNumber` guards on the
 * leaf `Link.to` AST.
 */
const transformWireKind = (schema: Schema.Top): "string" | "number" | undefined =>
  transformWireKindImpl(schema)

